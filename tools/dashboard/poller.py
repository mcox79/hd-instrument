"""Background poller: pulls dashboard data from marsh@home on a fixed cadence.

Keeps one in-memory snapshot, refreshed every POLL_INTERVAL_S. Endpoints read
the cached snapshot directly; they never touch the wire. On failure, the last
good snapshot stays available and the error is surfaced via /api/health.
"""

