_ORF_RE = re.compile(r"^Y[A-P][LR][0-9]{3}[WC](-[A-Z])?$")
_ROMAN = ["I", "II", "III", "IV", "V", "VI", "VII", "VIII", "IX", "X", "XI", "XII", "XIII", "XIV", "XV", "XVI"]


def is_wellformed_orf(orf):
    """True iff orf matches the canonical SGD systematic-ORF-name format (the shared canonical join key)."""
    return bool(_ORF_RE.match(str(orf).strip().upper()))


def chrom_of(orf):
    """Chromosome id DERIVED from the ORF id: 2nd char A-P -> chromosome I-XVI. Correct by construction (crisp)."""
    c = str(orf).strip().upper()[1]
    return "chr" + _ROMAN[ord(c) - ord("A")]


def generate_core_facts():
    """Return the LLM-generated factual-core triple list: (orf, relation, value, category, cross_check).

    Value entities are namespaced (PROT:/CPLX:/GO:/CHR:/CLASS:) so they never collide with gene ORF ids in the hub
    codebook. Relations restricted to the crispness allowlist; NO causal/severity relation is emitted."""
    facts = []
    for (orf, name, complex_id, process_id) in POPULATION:
        facts.append((orf, "is_a", "CLASS:protein_coding_gene", "taxonomic", "knowledge_based"))
        facts.append((orf, "encodes", "PROT:%s" % name, "compositional", "knowledge_based"))
        facts.append((orf, "part_of_complex", "CPLX:%s" % complex_id, "compositional", "knowledge_based"))
        facts.append((orf, "participates_in", "GO:%s" % process_id, "compositional", "knowledge_based"))
        facts.append((orf, "located_on", "CHR:%s" % chrom_of(orf), "quantitative_measured", "derived_from_orf_id"))
    return facts


# ---------------------------------------------------------------------------
# CONJUNCTION MODULE (structured genetic-interaction stand-in). Deterministic cross-pathway edge structure over the SAME
# ORF vocabulary. Offsets chosen so partner sets cross complex boundaries (=> proper-subset intersections with complex/
# process/chromosome property sets). EDGE STRUCTURE only (no epsilon magnitude), robust to the specific weights.
# ---------------------------------------------------------------------------
GENETIC_EDGE_OFFSETS = (3, 7, 11, 13)  # deterministic cross-complex link offsets over the sorted-ORF gene ordering


def module_orfs():
    """The MODULE tier's entity vocabulary = the SAME curated ORF ids (deterministic sorted order)."""
    return sorted(orf for (orf, _n, _c, _p) in POPULATION)


def generate_genetic_edges():
    """Return the conjunction-module genetic-interaction edge set as an undirected set of (orf_a, orf_b) ORF-string pairs.

    Deterministic: over the sorted-ORF gene ordering, gene i links to genes at fixed offsets (cross-complex), yielding
    partner sets that span multiple complexes. Symmetric (undirected); no self-edges."""
    orfs = module_orfs()
    v = len(orfs)
    edges = set()
    for i in range(v):
        for s in GENETIC_EDGE_OFFSETS:
            j = (i + s) % v
            if j == i:
                continue
            a, b = orfs[i], orfs[j]
            key = (a, b) if a < b else (b, a)
            edges.add(key)
    return sorted(edges)


