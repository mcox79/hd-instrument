# Self-test (constructs REAL items from REAL UD + REAL syntactic model; asserts arms + mechanics fire).
# ----------------------------------------------------------------------------------------------
def self_test():
    # 1) real extraction from real UD is deterministic + well-formed
    items = build_items()
    assert 30 <= len(items) <= MAX_ITEMS, f"expected 30..{MAX_ITEMS} items, got {len(items)}"
    for it in items:
        assert it["gold"] in ("V", "N")
        assert it["v"] and it["n1"] and it["prep"] and it["n2"]
        assert len({it["v"], it["n1"], it["n2"]}) >= 2, "content words should not all collapse"
    items2 = build_items()
    assert [tuple(sorted(i.items())) for i in items] == [tuple(sorted(i.items())) for i in items2], \
        "item build must be deterministic"

    # 2) REAL syntactic model built on real UD-train (exercises the fair baseline's real code path)
    syn_pred, maj_pred, stats = build_syntactic_model()
    assert stats["n_train_items"] > 100 and stats["n_preps"] > 5, "syntactic model must build on real train"
    assert maj_pred(items[0]) in ("V", "N")
    assert syn_pred(items[0]) in ("V", "N")
    acc_syn, _, _, _, _ = accuracy(items, syn_pred)
    assert 0.05 < acc_syn < 0.95, f"baseline must be in band, got {acc_syn}"

    # 3) binary mechanics + a toy rich table -> correct table scores high, scramble collapses it
    toy = [{"v": "see", "n1": "man", "prep": "with", "n2": "telescope", "gold": "V"},
           {"v": "see", "n1": "man", "prep": "with", "n2": "hat", "gold": "N"}]
    perfect = {"see|with|telescope": 0.9, "man|with|telescope": 0.2,
               "see|with|hat": 0.1, "man|with|hat": 0.85}
    rp = make_rich_pred(perfect, "N")
    acc_perfect, _, _, _, _ = accuracy(toy, rp)
    assert acc_perfect == 1.0, "a correct plausibility table must solve the classic telescope/hat 2-way"
    scr = make_scrambled_rich(perfect, "N")
    acc_scr, _, _, _, _ = accuracy(toy, scr)
    assert acc_scr <= acc_perfect, "scrambled must not exceed the correct table"
    rand = make_random_pred()
    acc_r, _, _, _, _ = accuracy(toy, rand)
    assert 0.0 <= acc_r <= 1.0
    # coverage f=0 must equal ARM_SYNTACTIC exactly (internal consistency of the curve)
    cov0 = make_rich_at_coverage(perfect, syn_pred, "N", 0.0)
    acc_cov0, _, _, _, _ = accuracy(items, cov0)
    assert abs(acc_cov0 - acc_syn) < 1e-9, "coverage f=0 must equal ARM_SYNTACTIC exactly"

    print(f"[{ANCHOR_NAME}] self-test PASS | n_items={len(items)} acc_syntactic={acc_syn:.3f} "
          f"maj_class={stats['maj_class']} n_train={stats['n_train_items']} "
          f"toy_perfect={acc_perfect} toy_scrambled={acc_scr} cov0==syn OK", flush=True)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--self-test", action="store_true")
    ap.add_argument("--dump-pairs", action="store_true")
    ap.add_argument("--smoke", action="store_true")
    ap.add_argument("--full", action="store_true")
    args = ap.parse_args()
    if args.self_test:
        self_test(); return
    if args.dump_pairs:
        dump_pairs("full"); return
    if args.smoke:
        run_mode("smoke"); return
    if args.full:
        run_mode("full"); return
    ap.error("specify one of --self-test | --dump-pairs | --smoke | --full")


