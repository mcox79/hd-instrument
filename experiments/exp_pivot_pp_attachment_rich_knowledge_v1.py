NOMINAL = {"NOUN", "PROPN"}


# ----------------------------------------------------------------------------------------------
# CoNLL-U reader (keeps lemma + deprel; the shared _ud_loader drops lemma which we need).
# ----------------------------------------------------------------------------------------------
def read_conllu(split):
    fp = os.path.join(UD_DIR, "en_ewt-ud-%s.conllu" % split)
    sents, cur = [], []
    with open(fp, encoding="utf-8") as f:
        for line in f:
            line = line.rstrip("\n")
            if not line:
                if cur:
                    sents.append(cur); cur = []
                continue
            if line.startswith("#"):
                continue
            c = line.split("\t")
            if len(c) < 8 or "-" in c[0] or "." in c[0]:
                continue
            try:
                idx = int(c[0]); head = int(c[6])
            except Exception:
                continue
            cur.append({"idx": idx, "form": c[1], "lemma": c[2], "upos": c[3], "head": head, "deprel": c[7]})
    if cur:
        sents.append(cur)
    return sents


def extract_ppa(split):
    """Extract ambiguous PP-attach quadruples (v, n1, prep, n2, gold in {V,N}) in linear order v<n1<prep<n2.
    Gold = UD attachment: obl->VERB = V; nmod->NOUN = N. The competing site must exist (genuine ambiguity)."""
    sents = read_conllu(split)
    items = []
    for sent in sents:
        by_idx = {t["idx"]: t for t in sent}
        children = defaultdict(list)
        for t in sent:
            children[t["head"]].append(t)
        for n2 in sent:
            if n2["upos"] not in NOMINAL:
                continue
            rel = n2["deprel"].split(":")[0]
            if rel not in ("obl", "nmod"):
                continue
            preps = [c for c in children[n2["idx"]]
                     if c["deprel"].split(":")[0] == "case" and c["upos"] == "ADP"]
            if len(preps) != 1:
                continue
            prep = preps[0]
            if prep["idx"] >= n2["idx"]:
                continue
            H = by_idx.get(n2["head"])
            if H is None:
                continue
            if rel == "obl" and H["upos"] == "VERB":
                gold = "V"; v = H
                objs = [c for c in children[v["idx"]]
                        if c["deprel"].split(":")[0] in ("obj", "dobj") and c["upos"] in NOMINAL
                        and v["idx"] < c["idx"] < prep["idx"]]
                if not objs:
                    continue
                n1 = max(objs, key=lambda t: t["idx"])          # nearest object noun before the prep
            elif rel == "nmod" and H["upos"] in NOMINAL:
                gold = "N"; n1 = H
                gv = by_idx.get(n1["head"])
                if gv is None or gv["upos"] != "VERB":
                    continue
                v = gv
            else:
                continue
            if not (v["idx"] < n1["idx"] < prep["idx"] < n2["idx"]):
                continue
            if len({v["idx"], n1["idx"], prep["idx"], n2["idx"]}) != 4:
                continue
            items.append({"v": v["lemma"].lower(), "n1": n1["lemma"].lower(),
                          "prep": prep["lemma"].lower(), "n2": n2["lemma"].lower(), "gold": gold})
    return items


def build_items():
    """Deterministic TEST item set, fixed-seed subsampled to MAX_ITEMS."""
    items = extract_ppa("test")
    items = sorted(items, key=lambda d: (d["v"], d["n1"], d["prep"], d["n2"], d["gold"]))
    if len(items) > MAX_ITEMS:
        rng = np.random.default_rng(SEED + 1)
        idx = sorted(rng.permutation(len(items))[:MAX_ITEMS].tolist())
        items = [items[i] for i in idx]
    return items


def triple_key(head, prep, n2):
    return f"{head}|{prep}|{n2}"


def unique_triples(items):
    """Flat sorted-then-shuffled deduped triple list -> what the LLM rates (UNLABELED, blind to gold)."""
    tset = set()
    for it in items:
        tset.add((it["v"], it["prep"], it["n2"], "verb"))
        tset.add((it["n1"], it["prep"], it["n2"], "noun"))
    ts = sorted(tset)
    rng = np.random.default_rng(SEED + 2)
    order = rng.permutation(len(ts)).tolist()
    return [{"head": ts[i][0], "prep": ts[i][1], "n2": ts[i][2], "head_pos": ts[i][3]} for i in order]


# ----------------------------------------------------------------------------------------------
# ARM_SYNTACTIC: prep-preference (Collins&Brooks-style) from the TRAIN extraction.
# ----------------------------------------------------------------------------------------------
def build_syntactic_model():
    tr = extract_ppa("train")
    pv = defaultdict(lambda: [0.0, 0.0])   # prep -> [V_count, total]
    nv = 0
    for i in tr:
        pv[i["prep"]][1] += 1
        if i["gold"] == "V":
            pv[i["prep"]][0] += 1; nv += 1
    glob_pV = nv / max(1, len(tr))
    maj_class = "V" if glob_pV > 0.5 else "N"

    def pV(prep):
        st = pv.get(prep)
        if st is None or st[1] < MIN_PREP_COUNT:
            return glob_pV
        return (st[0] + SMOOTH_K * glob_pV) / (st[1] + SMOOTH_K)

    def syn_pred(it):
        return "V" if pV(it["prep"]) > 0.5 else "N"

    def maj_pred(it):
        return maj_class
    return syn_pred, maj_pred, {"glob_pV": round(glob_pV, 4), "maj_class": maj_class,
                                "n_train_items": len(tr), "n_preps": len(pv)}


