def load_rich_table():
    if not os.path.exists(RICH_TABLE_PATH):
        return None
    with open(RICH_TABLE_PATH, encoding="utf-8") as f:
        obj = json.load(f)
    tab = {}
    for k, val in obj.get("ratings", obj).items():
        tab[k] = float(val)
    return tab


def make_rich_pred(rich_tab, maj_class):
    def pred(it):
        sv = rich_tab.get(triple_key(it["v"], it["prep"], it["n2"]))
        sn = rich_tab.get(triple_key(it["n1"], it["prep"], it["n2"]))
        sv = 0.5 if sv is None else sv
        sn = 0.5 if sn is None else sn
        if sv > sn:
            return "V"
        if sn > sv:
            return "N"
        return maj_class                       # tie -> majority (logged)
    return pred


def make_random_pred():
    rng = np.random.default_rng(SEED + 7)
    cache = {}

    def pred(it):
        k = (it["v"], it["n1"], it["prep"], it["n2"])
        if k not in cache:
            cache[k] = "V" if rng.random() < 0.5 else "N"
        return cache[k]
    return pred


def make_scrambled_rich(rich_tab, maj_class):
    keys = sorted(rich_tab.keys())
    vals = [rich_tab[k] for k in keys]
    rng = np.random.default_rng(SEED + 9)
    perm = rng.permutation(len(vals)).tolist()
    scr = {keys[i]: vals[perm[i]] for i in range(len(keys))}
    return make_rich_pred(scr, maj_class)


def make_rich_at_coverage(rich_tab, syn_pred, maj_class, f):
    """Keep fraction f of rich triples; item is rich-decided only if BOTH triples kept, else syntactic backoff."""
    keys = sorted(rich_tab.keys())
    rng = np.random.default_rng(SEED + 11)
    order = rng.permutation(len(keys)).tolist()
    keep = set(keys[order[i]] for i in range(int(round(f * len(keys)))))
    rp = make_rich_pred(rich_tab, maj_class)

    def pred(it):
        kv = triple_key(it["v"], it["prep"], it["n2"])
        kn = triple_key(it["n1"], it["prep"], it["n2"])
        if kv in keep and kn in keep:
            return rp(it)
        return syn_pred(it)
    return pred


def accuracy(items, pred_fn):
    """Returns accuracy, per-item correctness (1/0), per-item predictions, per-stratum-by-gold accuracy."""
    correct = 0
    per_item = []
    preds = []
    by_gold = defaultdict(lambda: [0, 0])
    for it in items:
        p = pred_fn(it)
        c = 1 if p == it["gold"] else 0
        correct += c
        per_item.append(c)
        preds.append(p)
        by_gold[it["gold"]][0] += c
        by_gold[it["gold"]][1] += 1
    acc = round(correct / max(1, len(items)), 4)
    strat = {g: round(v[0] / max(1, v[1]), 4) for g, v in sorted(by_gold.items())}
    strat_n = {g: v[1] for g, v in sorted(by_gold.items())}
    return acc, per_item, preds, strat, strat_n


