# ---------------------------------------------------------------------------
# GF(2^m) arithmetic
# ---------------------------------------------------------------------------

PRIMITIVE_POLY = {
    2: 0b111,
    3: 0b1011,
    4: 0b10011,
    5: 0b100101,
    6: 0b1000011,
    7: 0b10000011,
    8: 0b100011101,
}


def gf2m_mul_tables(m: int) -> tuple[np.ndarray, np.ndarray]:
    if m not in PRIMITIVE_POLY:
        raise ValueError(f"no primitive polynomial registered for GF(2^{m})")
    poly = PRIMITIVE_POLY[m]
    q = 1 << m
    period = q - 1
    antilog = np.zeros(period, dtype=np.int64)
    log_tab = -np.ones(q, dtype=np.int64)
    val = 1
    for i in range(period):
        antilog[i] = val
        log_tab[val] = i
        val <<= 1
        if val & q:
            val ^= poly
        val &= q - 1
    return log_tab, antilog


def gf_mul(a: int, b: int, log_tab: np.ndarray, antilog_tab: np.ndarray) -> int:
    if a == 0 or b == 0:
        return 0
    period = len(antilog_tab)
    return int(antilog_tab[(log_tab[a] + log_tab[b]) % period])


# ---------------------------------------------------------------------------
# Build q_b sign vectors (Kerdock-MM diagonal phase, char-2 quadratic form).
# ---------------------------------------------------------------------------
# Q_b(x) over F_2: identify x in {0,..,2^m - 1} as alpha in F_{2^m} via the
# standard basis {1, alpha, alpha^2, ..., alpha^{m-1}}. Then
#     Q_b(alpha) = Tr_{F_{2^m}/F_2}(b * alpha^2)
# in characteristic 2. This is a quadratic form: Tr(b * (alpha + beta)^2) =
# Tr(b * alpha^2) + Tr(b * beta^2) (since (alpha+beta)^2 = alpha^2 + beta^2
# in char 2, no cross term). Hence Q_b is in fact LINEAR over F_2 -- that
# yields a Pauli Z, not a Clifford-non-Pauli phase.
#
# The PROPER Kerdock quadratic phase uses a different form: pair up the m bits
# of x as a vector v in F_{2^{m/2}} x F_{2^{m/2}} (only works for even m) and
# use Q_b(v_lo, v_hi) = v_lo . (b * v_hi)   where . is dot product over F_2.
# This matches the substrate's `build_q_b_signs` in
# experiments/exp_wave14y_erase_kerdock_v3.py. We replicate it here verbatim.

def build_q_b_sign_vector(b: int, m: int, t: int, log_tab: np.ndarray,
                          antilog_tab: np.ndarray) -> np.ndarray:
    """Build the q_b in {+1, -1}^N sign vector for the Kerdock-MM quadratic
    form Q_b. Requires m = 2*t (even number of qubits) so that v in F_2^m
    splits as (v_lo, v_hi) in F_2^t x F_2^t identified with F_{2^t} x F_{2^t}.

    Q_b(v_lo, v_hi) = v_lo . (b * v_hi) over F_2.
    """
    if 2 * t != m:
        raise ValueError(f"m={m} must be 2*t for MM construction; got t={t}")
    N = 1 << m
    half_mask = (1 << t) - 1
    q = np.empty(N, dtype=np.float64)
    if b == 0:
        q.fill(1.0)
        return q
    for x in range(N):
        x_lo = x & half_mask
        x_hi = (x >> t) & half_mask
        pi_b_xhi = gf_mul(b, x_hi, log_tab, antilog_tab)
        bit_count = bin(x_lo & pi_b_xhi).count("1")
        q[x] = -1.0 if (bit_count & 1) else 1.0
    return q


# ---------------------------------------------------------------------------
# Single- and two-qubit gate constructors at m qubits
# ---------------------------------------------------------------------------

def hadamard_2() -> np.ndarray:
    return np.array([[1.0, 1.0], [1.0, -1.0]], dtype=np.complex128) / math.sqrt(2)


def phase_S_2() -> np.ndarray:
    return np.array([[1.0, 0.0], [0.0, 1j]], dtype=np.complex128)


def embed_single(U_local: np.ndarray, qubit: int, m: int) -> np.ndarray:
    """Embed 2x2 U_local at qubit `qubit` (LSB-indexed). Returns 2^m x 2^m unitary."""
    I = np.eye(2, dtype=np.complex128)
    ops = []
    for k in range(m - 1, -1, -1):
        ops.append(U_local if k == qubit else I)
    out = ops[0]
    for op in ops[1:]:
        out = np.kron(out, op)
    return out


def embed_cnot(ctrl: int, tgt: int, m: int) -> np.ndarray:
    """CNOT with control=ctrl, target=tgt on m qubits."""
    d = 1 << m
    U = np.zeros((d, d), dtype=np.complex128)
    for x in range(d):
        cb = (x >> ctrl) & 1
        tb = (x >> tgt) & 1
        new_tb = tb ^ cb
        y = (x & ~(1 << tgt)) | (new_tb << tgt)
        U[y, x] = 1.0
    return U


def hadamard_all(m: int) -> np.ndarray:
    """H^{otimes m}, the m-qubit all-Hadamard tensor."""
    H = hadamard_2()
    out = H
    for _ in range(m - 1):
        out = np.kron(out, H)
    return out


def diag_phase(sign_vec: np.ndarray) -> np.ndarray:
    """Diagonal unitary with diag entries = sign_vec (each +/-1)."""
    return np.diag(sign_vec.astype(np.complex128))


# ---------------------------------------------------------------------------
# Sampling random elements of each population
# ---------------------------------------------------------------------------

def sample_kerdock_unitary(rng: np.random.Generator, m: int,
                            q_b_table: list[np.ndarray],
                            H_all: np.ndarray,
                            word_length: int) -> np.ndarray:
    """Random word in {H_all} cup {diag(q_b) : b in F_{2^m}}.

    For the canonical Kerdock construction, the F_{2^m} translations T_b are
    the diagonal phases diag(q_b); the inversion W = [[0,1],[1,0]] lifts to
    H_all. PSL(2, F_{2^m}) is generated by these.
    """
    d = 1 << m
    U = np.eye(d, dtype=np.complex128)
    for _ in range(word_length):
        # Bias: with prob 1/2 apply H_all, else apply a random diag(q_b).
        if rng.random() < 0.5:
            U = H_all @ U
        else:
            b = int(rng.integers(0, len(q_b_table)))
            U = diag_phase(q_b_table[b]) @ U
    return U


def sample_clifford_unitary(rng: np.random.Generator, m: int,
                             word_length: int) -> np.ndarray:
    """Random word in {H_k, S_k, CNOT_{j,k}} of given length. Approaches uniform
    Clifford for word_length >> m^2 log m."""
    d = 1 << m
    U = np.eye(d, dtype=np.complex128)
    H = hadamard_2()
    Sg = phase_S_2()
    for _ in range(word_length):
        gate = int(rng.integers(0, 3))
        if gate == 0:
            k = int(rng.integers(0, m))
            G = embed_single(H, k, m)
        elif gate == 1:
            k = int(rng.integers(0, m))
            G = embed_single(Sg, k, m)
        else:
            if m == 1:
                # CNOT requires 2 qubits; fall back to H.
                G = embed_single(H, 0, m)
            else:
                ctrl = int(rng.integers(0, m))
                tgt = ctrl
                while tgt == ctrl:
                    tgt = int(rng.integers(0, m))
                G = embed_cnot(ctrl, tgt, m)
        U = G @ U
    return U


def sample_haar_unitary(rng: np.random.Generator, d: int) -> np.ndarray:
    """Mezzadri 2007: Haar-uniform on U(d)."""
    Z = (rng.standard_normal((d, d)) + 1j * rng.standard_normal((d, d))) / math.sqrt(2)
    Q, R = np.linalg.qr(Z)
    diag_R = np.diag(R)
    Lambda = diag_R / np.abs(diag_R)
    return Q * Lambda


# ---------------------------------------------------------------------------
# Self test
# ---------------------------------------------------------------------------

def _is_unitary(U: np.ndarray, tol: float = 1e-10) -> tuple[bool, float]:
    d = U.shape[0]
    err = np.max(np.abs(U @ U.conj().T - np.eye(d)))
    return bool(err < tol), float(err)


def self_test() -> None:
    # Build a small Kerdock q_b table at m=4 (t=2).
    log_tab, antilog_tab = gf2m_mul_tables(2)
    q_b_table = [build_q_b_sign_vector(b, m=4, t=2,
                                        log_tab=log_tab, antilog_tab=antilog_tab)
                 for b in range(4)]
    for b, qv in enumerate(q_b_table):
        assert qv.shape == (16,), f"q_b for b={b} wrong shape: {qv.shape}"
        assert np.all(np.abs(qv) == 1.0), f"q_b for b={b} not bipolar"
    print(f"[self-test] Kerdock q_b table built at m=4 t=2: {len(q_b_table)} cosets",
          flush=True)

    # H_all m=4 sanity
    H_all = hadamard_all(4)
    ok, err = _is_unitary(H_all)
    assert ok, f"H_all m=4 not unitary: err={err}"

    # Single H, S, CNOT unitary checks at m=3.
    H = hadamard_2()
    Sg = phase_S_2()
    HE = embed_single(H, 1, 3)
    SE = embed_single(Sg, 0, 3)
    CE = embed_cnot(0, 1, 3)
    for U, name in ((HE, "H_1"), (SE, "S_0"), (CE, "CNOT_01")):
        ok, err = _is_unitary(U)
        assert ok, f"{name} not unitary: err={err}"

    # Random Haar sample at d=8 unitary check.
    rng = np.random.default_rng(0)
    U = sample_haar_unitary(rng, 8)
    ok, err = _is_unitary(U)
    assert ok, f"Haar d=8 not unitary: err={err}"

    # Random Clifford sample at m=3, word=30 unitary check.
    U = sample_clifford_unitary(rng, 3, 30)
    ok, err = _is_unitary(U)
    assert ok, f"Clifford sample not unitary: err={err}"

    # Random Kerdock sample at m=4, word=30 unitary check.
    U = sample_kerdock_unitary(rng, 4, q_b_table, H_all, 30)
    ok, err = _is_unitary(U)
    assert ok, f"Kerdock sample not unitary: err={err}"

    print("[self-test] OK: all sample-routines produce unitaries.", flush=True)


# ---------------------------------------------------------------------------
# Per-group trace sampling
# ---------------------------------------------------------------------------

def sample_traces(group: str, m: int, n_samples: int, rng: np.random.Generator,
                  q_b_table: list[np.ndarray] | None,
                  H_all: np.ndarray | None,
                  kerdock_word_length: int,
                  clifford_word_length: int) -> np.ndarray:
    d = 1 << m
    traces = np.zeros(n_samples, dtype=np.complex128)
    for i in range(n_samples):
        if group == "kerdock":
            U = sample_kerdock_unitary(rng, m, q_b_table, H_all, kerdock_word_length)
        elif group == "clifford":
            U = sample_clifford_unitary(rng, m, clifford_word_length)
        elif group == "haar":
            U = sample_haar_unitary(rng, d)
        else:
            raise ValueError(f"unknown group: {group}")
        traces[i] = np.trace(U)
        if (i + 1) % max(1, n_samples // 10) == 0:
            print(f"    [{group}] {i + 1}/{n_samples}", flush=True)
    return traces


# ---------------------------------------------------------------------------
# Frame potential and verdict
# ---------------------------------------------------------------------------

def frame_potential(traces: np.ndarray) -> tuple[float, float]:
    abs4 = np.abs(traces) ** 4
    F = float(abs4.mean())
    se = float(abs4.std(ddof=1) / math.sqrt(len(abs4))) if len(abs4) > 1 else 0.0
    return F, se


def compute_verdict(summary: dict) -> tuple[str, str]:
    F_kerd = summary["F4"]["kerdock"]
    F_haar = summary["F4"]["haar"]
    F_cliff = summary["F4"]["clifford"]

    haar_band = (1.90, 2.10)
    cliff_band = (2.85, 3.15)

    haar_sanity_ok = abs(F_haar - 2.0) < 0.30

    if not haar_sanity_ok:
        return (
            "KERDOCK_2DESIGN_INCONCLUSIVE",
            f"Sampling-sanity FAIL: empirical Haar F_4={F_haar:.4f} far from 2.0. "
            f"Cannot trust comparison. Kerdock F_4={F_kerd:.4f}, "
            f"Clifford F_4={F_cliff:.4f}."
        )

    in_haar = haar_band[0] <= F_kerd <= haar_band[1]
    in_cliff = cliff_band[0] <= F_kerd <= cliff_band[1]

    if in_haar:
        return (
            "KERDOCK_2DESIGN_MATCH_HAAR",
            f"HARD PASS: Kerdock F_4={F_kerd:.4f} within +/-5% of Haar 2.0. "
            f"Substrate's Kerdock subgroup behaves like a unitary 2-design "
            f"(F_4 = 2). Refs: Haar F_4={F_haar:.4f}, Clifford F_4={F_cliff:.4f}."
        )
    if in_cliff:
        return (
            "KERDOCK_3DESIGN_MATCH_CLIFFORD",
            f"HARD PASS: Kerdock F_4={F_kerd:.4f} within +/-5% of Clifford 3.0. "
            f"Substrate's Kerdock subgroup inherits the Clifford 4-defect "
            f"(F_4 = 3). Refs: Haar F_4={F_haar:.4f}, Clifford F_4={F_cliff:.4f}."
        )
    return (
        "KERDOCK_ISOMORPHISM_BROKEN",
        f"HARD FAIL: Kerdock F_4={F_kerd:.4f} outside both Haar band {haar_band} "
        f"AND Clifford band {cliff_band}. Either (a) the q_b-based Kerdock "
        f"generating set is non-canonical and the substrate's Kerdock subgroup "
        f"is NOT the standard Clifford-2-design image of PSL(2, F_{{2^{m}}}), "
        f"or (b) the random-word mixing length was insufficient (run longer). "
        f"Refs: Haar F_4={F_haar:.4f}, Clifford F_4={F_cliff:.4f}. "
        f"Either outcome is informative: bug = fix; off-canonical = NEW finding."
    )


# ---------------------------------------------------------------------------
# Experiment driver
# ---------------------------------------------------------------------------

def run_experiment(smoke: bool, m: int = 6, n_samples: int = 10000,
                    seed: int = 0) -> tuple[dict, str, str, float, dict]:
    t0 = time.monotonic()
    if smoke:
        m = 4
        n_samples = 200
        seed = 42

    if m % 2 != 0:
        raise ValueError(f"m must be even for the Kerdock-MM construction; got m={m}")

    d = 1 << m
    t = m // 2
    kerdock_word_length = 6 * m  # mixing time for {H_all, T_b} on PSL(2, F_{2^m})
    clifford_word_length = 8 * m * m  # mixing time for Clifford generators

    config = {
        "m": m, "d": d, "t": t,
        "n_samples": n_samples,
        "seed": seed,
        "smoke": smoke,
        "kerdock_word_length": kerdock_word_length,
        "clifford_word_length": clifford_word_length,
        "groups": ["haar", "kerdock", "clifford"],
        "haar_band": [1.90, 2.10],
        "cliff_band": [2.85, 3.15],
    }
    print(f"[config] m={m} d={d} t={t} n_samples={n_samples} seed={seed} "
          f"smoke={smoke} kw_len={kerdock_word_length} cw_len={clifford_word_length}",
          flush=True)

    log_tab, antilog_tab = gf2m_mul_tables(t)
    q_b_table = [build_q_b_sign_vector(b, m, t, log_tab, antilog_tab)
                 for b in range(1 << t)]
    H_all = hadamard_all(m)
    print(f"[setup] q_b table: {len(q_b_table)} cosets at t={t}, "
          f"H_all shape {H_all.shape}", flush=True)

    rng = np.random.default_rng(seed)

    traces_all = {}
    F4 = {}
    F4_se = {}
    for group in config["groups"]:
        t_g = time.monotonic()
        print(f"\n[sampling] group={group} ...", flush=True)
        traces = sample_traces(group, m, n_samples, rng,
                                q_b_table=q_b_table, H_all=H_all,
                                kerdock_word_length=kerdock_word_length,
                                clifford_word_length=clifford_word_length)
        F, se = frame_potential(traces)
        F4[group] = F
        F4_se[group] = se
        traces_all[group] = {
            "n": int(len(traces)),
            "mean_abs2": float(np.mean(np.abs(traces) ** 2)),
            "mean_abs4": F,
            "se_abs4": se,
        }
        print(f"  [done] {group}: F_4 = {F:.5f} +/- {se:.5f}  "
              f"|Tr|^2 mean = {traces_all[group]['mean_abs2']:.5f}  "
              f"({time.monotonic() - t_g:.1f}s)", flush=True)

    devs = {
        "kerdock_vs_haar": (F4["kerdock"] - 2.0) / 2.0,
        "kerdock_vs_cliff": (F4["kerdock"] - 3.0) / 3.0,
        "kerdock_vs_haar_abs": F4["kerdock"] - 2.0,
        "kerdock_vs_cliff_abs": F4["kerdock"] - 3.0,
    }
    summary = {
        "F4": F4,
        "F4_se": F4_se,
        "deviations": devs,
        "traces_summary": traces_all,
    }
    verdict, msg = compute_verdict(summary)
    elapsed = time.monotonic() - t0
    print(f"\nVERDICT: {verdict}\n  {msg}", flush=True)
    return summary, verdict, msg, elapsed, config


# ---------------------------------------------------------------------------
# Metrics-write block (env-var-driven outdir + atomic write)
# ---------------------------------------------------------------------------

def get_output_dir(name: str) -> Path:
    env_name = os.environ.get("HDLAB_EXP_NAME", name)
    env_outdir = os.environ.get("HDLAB_OUTDIR")
    if env_outdir:
        out = Path(env_outdir)
    else:
        out = REPO / "data" / f"exp_{env_name}"
    out.mkdir(parents=True, exist_ok=True)
    return out


def validate_metrics(d: dict) -> None:
    required = {"verdict", "verdict_msg", "elapsed_s", "summary", "config"}
    missing = required - set(d.keys())
    if missing:
        raise ValueError(f"metrics missing required fields: {missing}")
    if not d.get("verdict"):
        raise ValueError("empty verdict")


def write_metrics(out_dir: Path, summary: dict, verdict: str, msg: str,
                   elapsed: float, config: dict) -> None:
    metrics = {
        "verdict": verdict,
        "verdict_msg": msg,
        "elapsed_s": elapsed,
        "summary": summary,
        "config": config,
    }
    validate_metrics(metrics)
    tmp = out_dir / "metrics.json.tmp"
    tmp.write_text(json.dumps(metrics, indent=2, default=float))
    tmp.replace(out_dir / "metrics.json")
    print(f"wrote {out_dir / 'metrics.json'}", flush=True)


def run_smoke() -> None:
    self_test()
    out_dir = get_output_dir("wave14_kerdock_2design_frame_potential_v1_smoke")
    summary, verdict, msg, elapsed, config = run_experiment(smoke=True)
    assert "haar" in summary["F4"], "smoke: missing Haar F_4"
    assert abs(summary["F4"]["haar"] - 2.0) < 0.5, (
        f"smoke FAIL: Haar F_4 = {summary['F4']['haar']:.3f} too far from 2.0"
    )
    write_metrics(out_dir, summary, verdict, msg, elapsed, config)
    print(f"\nSMOKE OK: verdict={verdict}; "
          f"F_4 Haar={summary['F4']['haar']:.3f} "
          f"Kerdock={summary['F4']['kerdock']:.3f} "
          f"Clifford={summary['F4']['clifford']:.3f}", flush=True)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--self-test", action="store_true")
    ap.add_argument("--smoke", action="store_true")
    ap.add_argument("--m", type=int, default=6,
                    help="qubit count (d = 2^m); default 6 (d=64). Must be even.")
    ap.add_argument("--n-samples", type=int, default=10000,
                    help="samples per group; default 10000")
    args = ap.parse_args()
    if args.self_test:
        self_test()
        return 0
    if args.smoke:
        run_smoke()
        return 0
    self_test()
    out_dir = get_output_dir("wave14_kerdock_2design_frame_potential_v1")
    summary, verdict, msg, elapsed, config = run_experiment(
        smoke=False, m=args.m, n_samples=args.n_samples
    )
    write_metrics(out_dir, summary, verdict, msg, elapsed, config)
    print(f"\nDONE: {verdict}", flush=True)
    return 0


