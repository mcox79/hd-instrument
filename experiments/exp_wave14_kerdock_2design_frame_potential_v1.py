"""Wave 14 -- Kerdock 2-design frame-potential probe (random-word formulation).

Question
--------
Is the substrate's Kerdock-derived unitary group a unitary 2-design (F_4 = 2)
or a 3-design (F_4 = 3) in the sense of Webb 2016 / Zhu 2017? The 4th frame
moment

    F_4(G) = E_{U ~ G} |Tr(U)|^4

distinguishes:
  - Haar measure on U(d):         F_4(Haar)   = 2 + O(1/d^2)
  - Full multi-qubit Clifford:    F_4(Cliff)  = 3 + O(1/d^2)
  - 2-design subgroup:            F_4 in [2, 3], closer to which baseline
    answers whether the subgroup achieves the Clifford 4-defect.

This script answers it empirically by sampling three populations of d x d
unitaries and computing the empirical F_4.

Group definitions (this script)
-------------------------------
Let d = 2^m for some m >= 4. Bipolar/qubit Clifford generators:
  H_k      : Hadamard on qubit k                       (2 x 2 H on qubit k)
  S_k      : phase gate diag(1, i) on qubit k
  CNOT_jk  : controlled-NOT, control j, target k
  Z_q_b    : "Kerdock-MM" diagonal +/-1 phase derived from a F_{2^m} element b
             via the quadratic form Q_b(x) = x . M_b x (over F_2), where M_b
             is the regular-representation matrix of "multiplication by b"
             in the trace-self-dual basis of F_{2^m}.

We sample three populations:

  1. KERDOCK -- random words in {W = H_all = H^{otimes m}} cup {Z_{q_b}: b in F_{2^m}}.
     This subgroup IS (up to global phase) the PSL(2, F_{2^m}) Clifford
     image in the canonical 2-design construction; it is generated by
     "translations" T_b = Z_{q_b} (the unipotent upper-triangular PSL elements
     [[1,b],[0,1]] lift to Z_{q_b} via the trace-self-dual basis) and the
     "inversion" W = H_all (the PSL element [[0,1],[1,0]] lifts to H^{otimes m}).
     A word of length L generates a near-uniform element of the subgroup once
     L exceeds the mixing time (~ O(m) for this generating set).

  2. CLIFFORD -- random words in {H_k, S_k, CNOT_{j,k}} of length 8 m^2.
     This is the full Clifford group; random words give near-uniform samples.
     Mixing time is O(m^2) by Bravyi-Maslov 2020 type arguments.

  3. HAAR -- Mezzadri 2007 QR construction from complex Gaussian matrices.

Implementation notes
--------------------
We work with dense d x d complex unitaries. At m = 6 (d = 64) each is a 64 KiB
complex128 matrix; storing 10K samples is ~640 MB peak. We instead stream:
sample, compute trace, discard. Per-sample cost is dominated by the gate
product (~ a few hundred d x d sparse matvec, or for the H_all gate one full
d x d dense multiply). At d = 64, 10K samples per group complete in well
under a minute on CPU.

Verdict policy
--------------
HARD PASS (Kerdock 2-design / 3-design isomorphism CONFIRMED):
  F_4(Kerdock) in [1.9, 2.1]  OR  F_4(Kerdock) in [2.85, 3.15]

HARD FAIL (isomorphism BROKEN):
  F_4(Kerdock) outside BOTH bands above.

Either outcome is informative. A HARD PASS confirms the Section 3.A claim;
a HARD FAIL is either an engineering bug or a substrate-novel finding
("the bipolar-encoded Kerdock falls off the canonical Clifford-2-design
path") -- worth its own deep drill.

Pre-reg: preregs/2026-05-23_wave14_kerdock_2design_frame_potential_v1.md
"""
