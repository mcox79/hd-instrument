"""
graph_node_classification_v1 -- Graph node classification via substrate prototype matching.

SCIENTIFIC QUESTION (from handoff: substrate-graph-gnn):
  Can the substrate classify graph nodes by community membership using Hebbian
  prototype learning, without a GNN?

  Mechanism: BSC channel model for node features.
    Each class c has a BSC prototype xi_c (random +-1 vector).
    Training node features: generated by flipping each bit of xi_c independently
    with probability p_flip = (1 - rho_within) / 2.
    W_c = sum_{j in class c} xi_j xi_j^T / N  (per-class Hebbian memory).
    Classification: argmax_c { xi_test^T W_c xi_test } (max dot product with W_c).

  Two cells:
  (A) Well-separated classes: rho_within=0.70 (30% bit flip rate).
      Expected accuracy >= 0.85.
  (B) Noisy classes: rho_within=0.60 (40% bit flip rate).
      Expected accuracy >= 0.65.

PRE-REGISTERED BANDS:
  HARD-PASS: accuracy_A >= 0.80 AND accuracy_B >= 0.60.
  MIDDLE: accuracy_A >= 0.65 AND accuracy_B >= 0.50.
  HARD-FAIL: accuracy_A < 0.65.

FORMULA SELF-TESTS:
  1. BSC bit-flip model: p_flip = (1 - rho_within) / 2.
     At rho_within=0.70: p_flip=0.15.
  2. Within-class score: xi_test^T W_c xi_test ~ n_c * rho_within^2 (leading order).
  3. Between-class score: ~ n_c * 0.25 (random BSC overlap ~ 0).
  4. SNR = rho_within^2 / (1/sqrt(n_c)) >> 1 at n_c=50, rho=0.70.

TIMEOUT ESTIMATE:
  Smoke: N=1024, n_train=200 (50/class), n_test=48 (12/class), 2 seeds.
  Full: N=1024, n_train=500 (125/class), n_test=80 (20/class), 5 seeds.
  Very fast. Smoke wall ~0.5s -> Full ~5s -> timeout=60s.
  No _nN suffix; production N=1024.
"""
import sys
sys.stdout.reconfigure(encoding='utf-8', errors='replace')
sys.stderr.reconfigure(encoding='utf-8', errors='replace')

import os
import argparse
import time
import json
import math
from pathlib import Path
from typing import Dict, Tuple

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from experiments._seed_checkpoint import get_output_dir

ANCHOR_NAME = "graph_node_classification_v1"
RUN_MODE = ("smoke" if "--smoke" in sys.argv else os.environ.get("HDLAB_RUN_MODE", "full")).lower()

N = 1024
C_CLASSES = 4

_ap = argparse.ArgumentParser()
_ap.add_argument("--smoke", action="store_true")
_ap.add_argument("--self-test", action="store_true")
_ARGS, _ = _ap.parse_known_args()

if RUN_MODE == "smoke":
    SEEDS = [7, 17]
    N_PER_CLASS_TRAIN = 50
    N_PER_CLASS_TEST = 12
else:
    SEEDS = [7, 17, 23, 31, 41]
    N_PER_CLASS_TRAIN = 125
    N_PER_CLASS_TEST = 20

# Cell A: well-separated
RHO_WITHIN_A = 0.70  # p_flip = 0.15

# Cell B: overlapping
RHO_WITHIN_B = 0.60  # p_flip = 0.20

# Pre-reg thresholds
HP_ACC_A = 0.80
HP_ACC_B = 0.60
MID_ACC_A = 0.65
MID_ACC_B = 0.50
HF_ACC_A = 0.65

# Formula self-test: p_flip at rho=0.70
_p_flip_test = (1.0 - 0.70) / 2.0
assert abs(_p_flip_test - 0.15) < 0.001, f"p_flip test: {_p_flip_test}"


def gen_bsc_pattern(prototype: np.ndarray, p_flip: float, rng: np.random.RandomState) -> np.ndarray:
    """BSC channel: flip each bit of prototype independently with probability p_flip."""
    pattern = prototype.copy()
    flips = rng.binomial(1, p_flip, size=len(prototype)).astype(bool)
    pattern[flips] *= -1
    return pattern


def run_cell(rho_within: float, n_train: int, n_test: int, N: int, C: int, seed: int) -> Tuple[float, int, int]:
    """Build per-class W matrices via BSC channel model, classify test nodes."""
    rng = np.random.RandomState(seed)
    p_flip = (1.0 - rho_within) / 2.0
    # Random BSC prototypes for each class
    prototypes = rng.choice([-1.0, 1.0], size=(C, N)).astype(np.float64)

    # Build per-class W matrices from training patterns
    W_list = []
    for c in range(C):
        Xi_c = np.stack([gen_bsc_pattern(prototypes[c], p_flip, rng) for _ in range(n_train)])
        W_list.append((Xi_c.T @ Xi_c) / N)

    # Classify test patterns
    n_correct = 0
    n_total = 0
    for c in range(C):
        for _ in range(n_test):
            xi_test = gen_bsc_pattern(prototypes[c], p_flip, rng)
            scores = [float(xi_test @ W_list[c2] @ xi_test) for c2 in range(C)]
            pred = int(np.argmax(scores))
            if pred == c:
                n_correct += 1
            n_total += 1

    return n_correct / n_total, n_correct, n_total


def run_seed(seed: int) -> Dict:
    # Cell A
    acc_A, correct_A, total_A = run_cell(RHO_WITHIN_A, N_PER_CLASS_TRAIN, N_PER_CLASS_TEST,
                                          N, C_CLASSES, seed)
    print(f"  [seed={seed} cell=A rho={RHO_WITHIN_A}] acc={acc_A:.4f} ({correct_A}/{total_A})",
          flush=True)

    # Cell B
    acc_B, correct_B, total_B = run_cell(RHO_WITHIN_B, N_PER_CLASS_TRAIN, N_PER_CLASS_TEST,
                                          N, C_CLASSES, seed + 500)
    print(f"  [seed={seed} cell=B rho={RHO_WITHIN_B}] acc={acc_B:.4f} ({correct_B}/{total_B})",
          flush=True)

    return {
        "cell_A_accuracy": acc_A, "cell_B_accuracy": acc_B,
        "seed": seed, "N": N, "run_mode": RUN_MODE,
    }


def _instrumentation_selftest():
    """Assert classification beats chance for well-separated classes."""
    acc, nc, nt = run_cell(0.70, 30, 10, 256, 4, 42)
    assert not math.isnan(acc), "accuracy is NaN"
    assert acc > 1.0 / 4, f"Below chance: acc={acc:.3f}"
    print(f"[selftest] PASS: node classification acc={acc:.4f} (chance=0.25) at N=256",
          flush=True)


_instrumentation_selftest()


def _verdict_formula_selftests():
    p_flip = (1.0 - 0.70) / 2.0
    assert abs(p_flip - 0.15) < 0.001, f"p_flip formula: {p_flip}"
    print("[formula_selftests] PASS: BSC p_flip formula verified", flush=True)


_verdict_formula_selftests()


def aggregate_results(per_seed: Dict) -> Dict:
    acc_A_vals = []
    acc_B_vals = []
    for sd in per_seed.values():
        acc_A_vals.append(sd["cell_A_accuracy"])
        acc_B_vals.append(sd["cell_B_accuracy"])
    return {
        "mean_acc_A": float(np.mean(acc_A_vals)) if acc_A_vals else float("nan"),
        "std_acc_A": float(np.std(acc_A_vals)) if len(acc_A_vals) > 1 else float("nan"),
        "mean_acc_B": float(np.mean(acc_B_vals)) if acc_B_vals else float("nan"),
        "std_acc_B": float(np.std(acc_B_vals)) if len(acc_B_vals) > 1 else float("nan"),
        "n_seeds": len(acc_A_vals),
        "rho_within_A": RHO_WITHIN_A,
        "rho_within_B": RHO_WITHIN_B,
    }


def compute_verdict(agg: Dict) -> Tuple[str, str]:
    acc_A = agg["mean_acc_A"]
    acc_B = agg["mean_acc_B"]
    if math.isnan(acc_A):
        return ("HARD_FAIL", "cell_A accuracy is NaN.")
    both_hp = acc_A >= HP_ACC_A and acc_B >= HP_ACC_B
    a_hf = acc_A < HF_ACC_A
    if both_hp:
        return ("HARD_PASS",
                f"Graph node classification confirmed. "
                f"cell_A acc={acc_A:.4f} (HP>={HP_ACC_A}) "
                f"cell_B acc={acc_B:.4f} (HP>={HP_ACC_B}). "
                f"BSC-channel prototype classifier operative at N={N}.")
    if a_hf:
        return ("HARD_FAIL",
                f"Node classification failed. cell_A acc={acc_A:.4f} < HF {HF_ACC_A}.")
    return ("MIDDLE_BAND",
            f"Partial node classification. cell_A acc={acc_A:.4f} cell_B acc={acc_B:.4f} "
            f"(HP: A>={HP_ACC_A} B>={HP_ACC_B}).")


def main():
    out_dir = get_output_dir(ANCHOR_NAME)
    t0 = time.time()
    print(f"[start] {ANCHOR_NAME} run_mode={RUN_MODE} N={N} C={C_CLASSES} "
          f"n_train_per_class={N_PER_CLASS_TRAIN} seeds={SEEDS}", flush=True)

    from experiments._seed_checkpoint import resumable_seeds, write_partial, aggregate_partials
    run_config = {"N": N, "run_mode": RUN_MODE}
    done, remaining = resumable_seeds(SEEDS, out_dir, run_config=run_config)
    print(f"[ckpt] {len(done)} done, {len(remaining)} remaining", flush=True)

    for seed in remaining:
        ts = time.time()
        result = run_seed(seed)
        write_partial(out_dir, seed, result)
        print(f"[seed {seed}] done in {time.time()-ts:.1f}s", flush=True)

    per_seed = aggregate_partials(out_dir, SEEDS)
    agg = aggregate_results(per_seed)
    verdict, verdict_msg = compute_verdict(agg)

    elapsed = time.time() - t0
    metrics = {
        "run_mode": RUN_MODE, "N": N, "C_CLASSES": C_CLASSES,
        "N_PER_CLASS_TRAIN": N_PER_CLASS_TRAIN, "N_PER_CLASS_TEST": N_PER_CLASS_TEST,
        "seeds": SEEDS, "aggregated": agg,
        "verdict": verdict, "verdict_msg": verdict_msg,
        "elapsed_s": elapsed,
    }
    out_dir.mkdir(parents=True, exist_ok=True)
    with open(out_dir / "metrics.json", "w") as f:
        json.dump(metrics, f, indent=2)
    print(f"[done] {verdict}: {verdict_msg}", flush=True)
    print(f"[done] elapsed={elapsed:.1f}s", flush=True)


if __name__ == "__main__":
    if _ARGS.self_test:
        print("[main] --self-test complete", flush=True)
        sys.exit(0)
    main()
