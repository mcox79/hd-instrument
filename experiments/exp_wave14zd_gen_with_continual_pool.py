def get_output_dir(default_name):
    name = os.environ.get("HDLAB_EXP_NAME", default_name)
    out = REPO / "data" / f"exp_{name}"
    out.mkdir(parents=True, exist_ok=True)
    return out


def validate_metrics(d):
    if not {"verdict", "verdict_msg", "elapsed_s", "summary", "config"}.issubset(d.keys()):
        raise ValueError("missing")


def generate_with_continual_pool(W, pool_vecs, pool_labels, pool_used, byte_atoms,
                                     pos_atoms, prefix_bytes, generate_length,
                                     n_dim, device, temperature, seed, pool_capacity):
    """Generate via sampling AND append each (ctx, generated) pair to pool."""
    K = v3.K
    context = list(prefix_bytes)
    generated = []
    gen_rng = torch.Generator(device=device).manual_seed(seed)
    pool_idx = pool_used % pool_capacity

    for step in range(generate_length):
        ctx_bytes = context[-K:]
        if len(ctx_bytes) < K:
            ctx_bytes = [v3.PAD_BYTE] * (K - len(ctx_bytes)) + ctx_bytes
        idx_tensor = torch.tensor([ctx_bytes], dtype=torch.long, device=device)
        ctx = v3.build_ctx(byte_atoms, pos_atoms, idx_tensor)
        q = ctx @ W.T
        q = v3.shifted_relu(q, v3.RELU_B)
        sims = (byte_atoms @ q.T) / n_dim
        P_W = torch.softmax(yy.BETA * sims / temperature, dim=0).squeeze(1)
        if pool_used > 0 and yy.ALPHA > 0:
            active = pool_vecs[:pool_used]
            labels = pool_labels[:pool_used]
            sims_p = (active @ ctx.T) / n_dim
            weights_p = torch.softmax(yy.BETA * sims_p / temperature, dim=0).squeeze(1)
            P_retr = torch.zeros(v3.VOCAB_SIZE, device=device)
            P_retr.scatter_add_(0, labels, weights_p)
            P = yy.ALPHA * P_retr + (1 - yy.ALPHA) * P_W
        else:
            P = P_W
        next_byte = int(torch.multinomial(P, 1, generator=gen_rng).item())
        generated.append(next_byte)
        context.append(next_byte)

        # Continual: append (ctx, generated) to pool with FIFO eviction
        pool_vecs[pool_idx % pool_capacity] = ctx.squeeze(0)
        pool_labels[pool_idx % pool_capacity] = next_byte
        pool_idx = (pool_idx + 1) % pool_capacity
        pool_used = min(pool_used + 1, pool_capacity)

    return generated, pool_used


def compute_verdict(summary):
    static_e = summary.get("static_entropy")
    static_r = summary.get("static_repetition")
    continual_e = summary.get("continual_entropy")
    continual_r = summary.get("continual_repetition")
    if static_e is None or continual_e is None:
        return ("GEN_POOL_INCONCLUSIVE", "Missing.")

    static_ok = (yy.PASS_ENTROPY_LOW <= static_e <= yy.PASS_ENTROPY_HIGH
                  and static_r < yy.PASS_REPETITION)
    continual_ok = (yy.PASS_ENTROPY_LOW <= continual_e <= yy.PASS_ENTROPY_HIGH
                     and continual_r < yy.PASS_REPETITION)

    if continual_ok and static_ok:
        if continual_e > static_e + 0.3 or continual_r < static_r - 0.05:
            return ("GEN_POOL_IMPROVES",
                    f"Continual pool generation produces MORE diverse output than "
                    f"static pool: entropy {continual_e:.3f} vs {static_e:.3f}, "
                    f"repetition {continual_r:.3f} vs {static_r:.3f}. Real-time "
                    f"learning improves generation quality.")
        return ("GEN_POOL_BOTH_WORK",
                f"Both static and continual pool produce non-degenerate generation. "
                f"static=(e={static_e:.3f},r={static_r:.3f}); "
                f"continual=(e={continual_e:.3f},r={continual_r:.3f}). "
                f"Continual pool doesn't measurably help (already at substrate limit).")
    if not continual_ok:
        return ("GEN_POOL_COLLAPSE",
                f"Continual pool causes generation to collapse: entropy="
                f"{continual_e:.3f}, repetition={continual_r:.3f}. Self-trained pool "
                f"degrades quality.")
    return ("GEN_POOL_STATIC_BROKEN",
            f"Static pool broken (e={static_e:.3f},r={static_r:.3f}) but continual "
            f"works. Surprising; audit.")


def self_test_verdict():
    cases = [
        ({"static_entropy": 5.0, "static_repetition": 0.05,
          "continual_entropy": 5.5, "continual_repetition": 0.0},
         "GEN_POOL_IMPROVES"),
        ({"static_entropy": 5.0, "static_repetition": 0.05,
          "continual_entropy": 5.1, "continual_repetition": 0.05},
         "GEN_POOL_BOTH_WORK"),
        ({"static_entropy": 5.0, "static_repetition": 0.05,
          "continual_entropy": 1.5, "continual_repetition": 0.95},
         "GEN_POOL_COLLAPSE"),
        ({}, "GEN_POOL_INCONCLUSIVE"),
    ]
    for s, exp in cases:
        a, _ = compute_verdict(s)
        if a != exp: raise AssertionError(f"{a} != {exp}")
    print(f"verdict self-test passed (4/4 cases)", flush=True)


def run_experiment(smoke):
    t0 = time.monotonic()
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    n_dim = yy.N_SMOKE if smoke else yy.N_FULL
    gen_len = yy.GENERATE_LENGTH_SMOKE if smoke else yy.GENERATE_LENGTH_FULL
    max_epochs = yy.MAX_EPOCHS_SMOKE if smoke else yy.MAX_EPOCHS_FULL
    T = 1.0
    seed = 17

    config = {"mode": "smoke" if smoke else "full", "N": n_dim,
              "generate_length": gen_len, "temperature": T,
              "max_epochs": max_epochs}
    print(f"[config] {config}", flush=True)

    corpus_a = v3.load_corpus_a()
    train_a = corpus_a[:int(0.8 * len(corpus_a))]
    if smoke:
        train_a = train_a[:4000]
    gen_rng = torch.Generator().manual_seed(seed)
    byte_atoms = v3.make_bsc_atoms(v3.VOCAB_SIZE, n_dim, gen_rng).to(device)
    pos_atoms = v3.make_bsc_atoms(v3.K, n_dim, gen_rng).to(device)
    W, pool_A, labels_A, used_A = v3.train_phase_a(
        byte_atoms, pos_atoms, train_a, n_dim, max_epochs, yy.BATCH_SIZE)
    pool_capacity = pool_A.size(0)

    prefix_bytes = list(corpus_a[:yy.PREFIX_LENGTH])

    # Static pool generation
    static_gen = yz.generate_sampled(W, pool_A, labels_A, used_A, byte_atoms, pos_atoms,
                                         prefix_bytes, gen_len, n_dim, device, T, seed)
    static_e = yy.char_entropy(static_gen)
    static_r = yy.ngram_repetition_rate(static_gen, n=4)

    # Continual pool generation
    pool_B = pool_A.clone()
    labels_B = labels_A.clone()
    continual_gen, _ = generate_with_continual_pool(W, pool_B, labels_B, used_A,
                                                        byte_atoms, pos_atoms, prefix_bytes,
                                                        gen_len, n_dim, device, T,
                                                        seed + 1, pool_capacity)
    continual_e = yy.char_entropy(continual_gen)
    continual_r = yy.ngram_repetition_rate(continual_gen, n=4)

    summary = {
        "static_entropy": static_e, "static_repetition": static_r,
        "continual_entropy": continual_e, "continual_repetition": continual_r,
        "static_sample": bytes(static_gen[:200]).decode("utf-8", errors="replace"),
        "continual_sample": bytes(continual_gen[:200]).decode("utf-8", errors="replace"),
    }
    verdict, msg = compute_verdict(summary)
    elapsed = time.monotonic() - t0
    print(f"\nstatic: entropy={static_e:.3f} repetition={static_r:.3f}", flush=True)
    print(f"continual: entropy={continual_e:.3f} repetition={continual_r:.3f}", flush=True)
    print(f"\nVERDICT: {verdict}\n  {msg}", flush=True)
    return summary, verdict, msg, elapsed, config


def write_metrics(out_dir, summary, verdict, msg, elapsed, config):
    metrics = {"verdict": verdict, "verdict_msg": msg, "elapsed_s": elapsed,
                "summary": summary, "config": config}
    validate_metrics(metrics)
    tmp = out_dir / "metrics.json.tmp"
    tmp.write_text(json.dumps(metrics, indent=2, default=float))
    tmp.replace(out_dir / "metrics.json")


def run_smoke():
    out_dir = get_output_dir("wave14zd_gen_with_continual_pool_smoke")
    summary, verdict, msg, elapsed, config = run_experiment(smoke=True)
    write_metrics(out_dir, summary, verdict, msg, elapsed, config)
    print(f"\nSMOKE OK: {verdict}", flush=True)


def run_main():
    out_dir = get_output_dir("wave14zd_gen_with_continual_pool")
    summary, verdict, msg, elapsed, config = run_experiment(smoke=False)
    write_metrics(out_dir, summary, verdict, msg, elapsed, config)
    print(f"\nDONE: {verdict}", flush=True)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--self-test", action="store_true")
    ap.add_argument("--smoke", action="store_true")
    args = ap.parse_args()
    if args.self_test: self_test_verdict(); return 0
    if args.smoke: run_smoke(); return 0
    run_main(); return 0


if __name__ == "__main__":
    sys.exit(main())
