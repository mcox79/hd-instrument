def v169_schur_mass_empirical(codebook: np.ndarray, n: int) -> dict:
    """Run v169's empirical Schur-Weyl mass computation on the codebook.

    Computes eig((1/N) A^T A) then uses schur_weyl_irrep_masses. This is the
    O(N^3) baseline we want to reproduce via the Clifford-TN closed form.
    """
    M, N = codebook.shape
    # Compute the M-eigenvalue spectrum of (1/N) A A^T (= (1/N) A^T A when M=N).
    # We use A @ A.T (small dimension when M = 2N) and divide by N.
    gram = (codebook @ codebook.T) / N  # (M, M); for Kerdock 2-coset M=2N.
    eig = np.linalg.eigvalsh(gram)
    eig = np.clip(eig, 0.0, None)  # eliminate numerical-negative noise
    return schur_weyl_irrep_masses(eig, n)


