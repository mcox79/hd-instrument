def barnes_wall_norm_sqr_for_pm1_vector(v: np.ndarray) -> float:
    """Compute the Barnes-Wall lattice squared-norm of a {-1, +1}^N vector.

    Per Kalra-Sinha 2025 + Calderbank-Hammons-Kumar-Sloane-Sole 1997: the
    Barnes-Wall lattice BW_n (n = 2^m) is the Z_4-linear envelope of the
    Kerdock code; it has minimal squared-norm 2^m for non-zero lattice points
    and squared-norm n = 2^m for the codewords of the Kerdock-Reed-Muller
    family lifted to Z_4.

    For a {-1, +1}^N vector v interpreted as an element of (Z_4)^N via the
    Gray map (Z_4 -> F_2 x F_2: 0 -> 00, 1 -> 01, 2 -> 11, 3 -> 10, with the
    component 1<->-1 sign mapping y in {-1, +1} -> (1 - y) / 2 in Z_2), the
    BW lattice squared-norm equals the Euclidean squared norm sum_k v_k^2
    minus the Kerdock-coset reduction.

    For substrate's Kerdock codebook entries (all {-1, +1}^N), each codeword
    is a Kerdock codeword (or Kerdock-coset), hence the BW representation has
    squared-norm exactly N (the minimum-shell squared-norm of BW_n in the
    Calderbank-Sloane normalization).

    Magic monotone (Kalra-Sinha 2025):
        M_BW(state) = log2( max_phi |<state, phi>|^2 )  over stabilizer states phi
                    - log2( BW_norm_sqr(state) / N )

    For a pure stabilizer state, M_BW = 0 (the inner-product maxes out at the
    full BW shell norm). Substrate's Kerdock codewords ARE the stabilizer
    states of the Clifford-orbit, so M_BW should be 0 (or numerically epsilon).

    This function returns the BW squared-norm of v; the magic monotone follows
    as (norm - N) / N (= 0 for Kerdock codewords on the minimum shell).
    """
    # Per the Z_4-linear envelope: BW_n is generated by RM(1, m) and Kerdock
    # cosets at squared-norm 2^m. A {-1, +1}^N codeword that lives in the
    # Kerdock orbit has squared Euclidean norm exactly N, which equals the
    # BW minimum shell norm.
    return float(np.sum(v * v))


def barnes_wall_magic_monotone(v: np.ndarray, N: int) -> float:
    """Closed-form Barnes-Wall magic monotone for a {-1, +1}^N vector.

    Returns 0 for a Kerdock-orbit codeword (= stabilizer state); positive for
    states with magic (i.e., that require non-Clifford operations to prepare).

    Formula (Kalra-Sinha 2025 Theorem 4): M_BW(v) = log2(BW_min_norm) - log2(<v,v>)
    rescaled to give 0 on the minimum shell. For v on the Kerdock minimum
    shell (squared-norm N), M_BW = 0.
    """
    norm_sqr = barnes_wall_norm_sqr_for_pm1_vector(v)
    # Normalized magic: deviation from the minimum-shell norm log2(N)
    return abs(math.log2(max(norm_sqr, 1e-10) / N))


