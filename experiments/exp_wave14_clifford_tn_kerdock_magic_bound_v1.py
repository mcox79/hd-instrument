def self_test_barnes_wall_norm_on_stabilizer_state() -> None:
    """SELF-TEST 1: BW norm = N for an N-bit {+1}^N stabilizer state |0>^N."""
    for N in [4, 8, 16, 64]:
        v = np.ones(N)
        norm_sqr = barnes_wall_norm_sqr_for_pm1_vector(v)
        assert abs(norm_sqr - N) < 1e-12, f"BW norm of |0>^{N} = {norm_sqr}, expected {N}"
        magic = barnes_wall_magic_monotone(v, N)
        assert magic < 1e-12, f"|0>^{N} magic = {magic}, expected 0"


