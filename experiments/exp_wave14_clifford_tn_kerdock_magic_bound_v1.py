    # Slope check: log(t_N / t_0) / log(N / N_0)
    if v169_t0 > 1e-9 and v169_tn > 1e-9 and nfin > n0:
        v169_slope = math.log(v169_tn / v169_t0) / math.log(nfin / n0)
    else:
        v169_slope = float("nan")
    if tn_t0 > 1e-9 and tn_tn > 1e-9 and nfin > n0:
        tn_slope = math.log(tn_tn / tn_t0) / math.log(nfin / n0)
    else:
        tn_slope = float("nan")

    metrics = {
        "verdict": verdict,
        "verdict_msg": verdict_msg,
        "elapsed_s": elapsed,
        "summary": {
            "N_list": N_list,
            "n_orders": n_orders,
            "max_rel_err": max(
                r["per_n"][n]["rel_err_max"] for r in experiment_data["results"] for n in n_orders
            ),
            "max_magic_monotone": max(r["magic_max_over_seeds"] for r in experiment_data["results"]),
            "v169_time_scaling_slope": v169_slope,
            "tn_time_scaling_slope": tn_slope,
            "scaling_check_v169_to_tn_speedup_at_largest_N": tn_t0 / max(tn_tn, 1e-9) if False else float(
                experiment_data["results"][-1]["per_n"][n_orders[0]]["speedup_mean"]
            ),
        },
        "config": {
            "N_list": N_list,
            "n_orders": n_orders,
            "seeds": seeds,
            "smoke": bool(args.smoke),
        },
        "results_per_N": experiment_data["results"],
    }

    validate_metrics(metrics)
    out_path = out_dir / "metrics.json"
    write_metrics_atomic(out_path, metrics)
    print(f"[done] wrote {out_path}")


