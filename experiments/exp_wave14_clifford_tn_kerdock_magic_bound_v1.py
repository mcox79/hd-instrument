def clifford_tn_schur_mass(codebook: np.ndarray, n: int) -> dict:
    """Compute Schur-Weyl irrep masses via the Clifford-TN bond-dim-1 closed form.

    Per Lami-Haug-De Nardis 2025: a Kerdock codeword (Clifford-orbit) at
    bond-dim chi=1 has the spectral measure of (1/N) A^T A equal to a SUM OF
    DELTA MEASURES at the squared singular values, which for a Kerdock 2-coset
    codebook (M = 2N codewords) are:

      - rank-N component:   the Hadamard coset (orthogonal rows), giving N
                            eigenvalues = N / N = 1.0 (uniform).
      - rank-N component:   the bent-twisted coset, giving N eigenvalues = 1.0.

    Total: 2N eigenvalues, all = 1.0.  Spectral measure delta(lambda - 1).

    Power sums: p_k = (1/(2N)) sum lambda_i^k = 1.0 for all k.
    Schur polynomial s_lambda(1, 1, ..., 1) = dim(irrep lambda) / n!.

    This is the CLOSED-FORM expected output of v169 for a pure Kerdock 2-coset
    codebook. The TN claim is that this closed-form (O(N log N) to compute the
    codebook + O(1) for the spectrum) matches v169's O(N^3) SVD-based output.
    """
    M, N = codebook.shape
    # For Kerdock 2-coset: all rows are pairwise orthogonal within a coset; cross-
    # coset inner products are +- N/sqrt(N) = +-sqrt(N) per pair (Welch bound).
    # The eigenvalues of (1/N) A^T A are all 1.0 (uniform) when M = 2N because
    # A^T A = 2 * I_N (each coset contributes I_N).
    #
    # Power sums of the spectral measure: p_k = mean(lambda^k) = 1.0 for all k.
    power_sums = [1.0] * n

    parts = integer_partitions(n)
    s_vals = []
    for lam in parts:
        # s_lambda(p_1=1, ..., p_n=1) = dim(irrep lambda) at one variable; or
        # more precisely s_lambda evaluated at power sums all = 1 gives the
        # number of standard Young tableaux of shape lam (by Frobenius
        # character formula and the hook-length normalization). We re-use
        # v169's schur_polynomial_in_power_sums for consistency.
        s_val = _v169.schur_polynomial_in_power_sums(lam, power_sums)
        s_vals.append(s_val)

    s_pos = [max(0.0, s) for s in s_vals]
    total = sum(s_pos)
    if total <= 0:
        masses = [0.0 for _ in parts]
    else:
        masses = [s / total for s in s_pos]

    mass_n = 0.0
    mass_singletons = 0.0
    for i, lam in enumerate(parts):
        if lam == (n,):
            mass_n = masses[i]
        if all(x == 1 for x in lam):
            mass_singletons = masses[i]

    return {
        "partitions": [list(p) for p in parts],
        "s_lambda": s_vals,
        "masses": masses,
        "mass_n": mass_n,
        "mass_111": mass_singletons,
        "method": "clifford_tn_bond_dim_1_closed_form",
    }


