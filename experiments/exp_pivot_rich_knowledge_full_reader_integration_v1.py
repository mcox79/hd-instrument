# Candidate construction: the reader's REAL candidates, junk-funcword dropped (shared across arms).
# Each candidate record carries sid, verb surface + lemma, agent, patient, structural feat.
# =======================================================================================
def build_candidates(slice_lessons):
    order, sent_text, reader_svo = L.load_slice_and_reader(slice_lessons)
    gold, meta = L.load_gold(slice_lessons)
    cands = []                                  # flat list of candidate dicts
    by_inst = defaultdict(list)                 # (sid, v_lemma) -> list of candidate indices into cands
    for sid in order:
        toks = L.tokenize(sent_text[sid])
        for (v, a, p) in reader_svo[sid]:
            feat, _ = L.candidate_features(toks, v, p)
            if feat[4] >= 0.5:                  # f_func: funcword / non-alpha junk patient -> drop (shared)
                continue
            vl = L.lemma_verb(v)
            rec = {"sid": sid, "v_surf": v, "v": vl, "a": a, "p": p, "feat": feat}
            by_inst[(sid, vl)].append(len(cands))
            cands.append(rec)
    return order, sent_text, reader_svo, gold, meta, cands, by_inst


def unique_pairs(cands):
    """Sorted-then-shuffled deduped (verb_lemma, noun) list -> what the LLM rates (UNLABELED, blind to gold)."""
    pairs = sorted(set((c["v"], c["p"]) for c in cands))
    rng = np.random.default_rng(SEED + 2)
    order = rng.permutation(len(pairs)).tolist()
    return [{"verb": pairs[i][0], "noun": pairs[i][1]} for i in order]


