# Self-test (EXERCISES the REAL reader candidates + REAL GloVe teacher + REAL score_arm at tiny scale).
# =======================================================================================
def self_test():
    import inspect
    # F.2 substrate_signature: bind against LIVE LCCP signatures (base/stable API only).
    for fn, kws in [(L.load_slice_and_reader, ["slice_lessons"]),
                    (L.load_gold, ["slice_lessons"]),
                    (L.candidate_features, ["toks", "v_surf", "p_surf"]),
                    (L.build_semantic_teacher, ["cands", "glove"])]:
        params = inspect.signature(fn).parameters
        for kw in kws:
            assert kw in params, f"signature drift: {fn.__name__} missing {kw!r} ({list(params)})"
    assert "kept" in inspect.signature(L.score_arm).parameters

    # F.1 real_code_path: construct REAL candidates + REAL thin teacher + REAL scoring on the SMOKE slice.
    order, sent_text, reader_svo, gold, meta, cands, by_inst = build_candidates(SMOKE_SLICE)
    assert len(cands) > 5, f"expected real reader candidates, got {len(cands)}"
    thin, stats = build_thin_sel(cands, SMOKE_SLICE)
    assert stats["glove_terms"] > 0, "GloVe teacher must load real vectors"
    s0 = thin(cands[0]["v"], cands[0]["p"])
    assert isinstance(s0, float), "thin sel returns float"
    assert thin("qzxwv", "qzxwv") == 0.0, "OOV thin backs off to 0.0"

    # discriminating set + argmax pick mechanics on the REAL reader.
    D = discriminating_set(gold, by_inst, cands)
    a_thin, pv = disambig_accuracy(thin, D, cands)
    assert 0.0 <= a_thin <= 1.0 and len(pv) == len(D)

    # F1 sweep on the REAL scorer; reader-raw reference computes.
    sweep, bq = f1_sweep(thin, cands, by_inst, gold)
    assert len(sweep) == EXPECTED_Q_POINTS
    kept_raw = [(c["sid"], (c["v_surf"], c["a"], c["p"])) for c in cands]
    sc_raw = L.score_arm(kept_raw, gold)
    assert "f1" in sc_raw

    # toy rich table -> arms differ + scramble does not exceed a rigged-perfect table + OOV backs off to thin.
    toy_tab = {(cands[0]["v"], cands[0]["p"]): 0.99}
    rich = build_rich_sel(toy_tab, thin)
    assert rich(cands[0]["v"], cands[0]["p"]) == 0.99, "rich uses table where present"
    assert rich("qzxwv", "qzxwv") == thin("qzxwv", "qzxwv"), "rich OOV backs off to thin"
    scr = build_scrambled_sel(toy_tab, thin)
    assert isinstance(scr(cands[0]["v"], cands[0]["p"]), float)
    rnd = build_random_sel()
    a_rnd, _ = disambig_accuracy(rnd, D, cands)
    assert 0.0 <= a_rnd <= 1.0

    # determinism: rebuild candidates -> identical order + pairs.
    o2, s2, r2, g2, m2, c2, b2 = build_candidates(SMOKE_SLICE)
    assert [(c["sid"], c["v"], c["p"]) for c in cands] == [(c["sid"], c["v"], c["p"]) for c in c2], \
        "candidate build must be deterministic"

    print(f"[{ANCHOR_NAME}] self-test PASS | cands={len(cands)} |D|={len(D)} disambig_thin={a_thin:.3f} "
          f"glove={stats['glove_terms']} raw_F1={sc_raw['f1']:.3f} best_q={bq} arms/scramble/OOV OK", flush=True)
    return 0


