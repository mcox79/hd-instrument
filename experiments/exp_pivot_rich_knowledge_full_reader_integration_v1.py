def build_thin_sel(cands, slice_lessons):
    """The reader's REAL GloVe selectional coherence teacher (build_semantic_teacher), reused VERBATIM."""
    toks_all = []
    _, sent_text, _ = L.load_slice_and_reader(slice_lessons)
    for s in sent_text.values():
        toks_all.extend(L.tokenize(s))
    glove = L.load_glove_for(sorted(set(toks_all)))
    teacher_cands = [{"sid": c["sid"], "v": c["v"], "a": c["a"], "p": c["p"], "feat": c["feat"]} for c in cands]
    sel_fn, verb_cent, glob_cent = L.build_semantic_teacher(teacher_cands, glove)

    def thin(v, p):
        s = sel_fn(v, p)
        return 0.0 if s is None else float(s)     # OOV -> 0.0 (no coherence signal = the poverty)
    return thin, {"n_verb_centroids": len(verb_cent), "glove_terms": len(glove)}


def load_rich_table():
    if not os.path.exists(RICH_TABLE_PATH):
        return None
    with open(RICH_TABLE_PATH, encoding="utf-8") as f:
        obj = json.load(f)
    tab = {}
    for k, val in obj.get("ratings", obj).items():
        if "|" in k:
            v, n = k.split("|", 1)
            tab[(v, n)] = float(val)
    return tab


def build_rich_sel(rich_tab, thin):
    """ARM_RICH: rich table lookup; OOV backs off to THIN (isolates the added rich knowledge)."""
    def rich(v, p):
        r = rich_tab.get((v, p))
        return thin(v, p) if r is None else float(r)
    return rich


def build_scrambled_sel(rich_tab, thin):
    keys = sorted(rich_tab.keys())
    vals = [rich_tab[k] for k in keys]
    rng = np.random.default_rng(SEED + 9)
    perm = rng.permutation(len(vals)).tolist()
    scr = {keys[i]: vals[perm[i]] for i in range(len(keys))}

    def s(v, p):
        r = scr.get((v, p))
        return thin(v, p) if r is None else float(r)
    return s


def build_random_sel():
    rng = np.random.default_rng(SEED + 7)
    cache = {}

    def s(v, p):
        k = (v, p)
        if k not in cache:
            cache[k] = float(rng.random())
        return cache[k]
    return s


# =======================================================================================
# (1) DISAMBIGUATION accuracy (threshold-free) over the discriminating set D.
# =======================================================================================
def discriminating_set(gold, by_inst, cands):
    """D = gold-pos verb instances where gold patient IS a candidate AND >=2 candidates (genuine competition)."""
    D = []
    for sid, rec in gold.items():
        for g in rec["pos"]:
            idxs = by_inst.get((sid, g["v"]), [])
            patients = [cands[i]["p"] for i in idxs]
            if g["patient"] in patients and len(set(patients)) >= 2:
                D.append({"sid": sid, "v": g["v"], "gold_patient": g["patient"], "cand_idxs": idxs})
    return D


def argmax_pick(sel, cands, idxs):
    """Pick the candidate index with max sel; deterministic first-wins tie-break by reading order (idxs sorted)."""
    best_i, best_s = None, None
    for i in idxs:
        c = cands[i]
        s = sel(c["v"], c["p"])
        if best_s is None or s > best_s:
            best_s, best_i = s, i
    return best_i, best_s


def disambig_accuracy(sel, D, cands):
    correct = 0
    per = []
    for d in D:
        bi, _ = argmax_pick(sel, cands, d["cand_idxs"])
        pick = cands[bi]["p"] if bi is not None else None
        ok = (pick == d["gold_patient"])
        correct += 1 if ok else 0
        per.append(1 if ok else 0)
    return (correct / len(D) if D else 0.0), per


# =======================================================================================
# (2) FULL patient-F1 via argmax-sel keep with a per-arm quantile threshold (shared q = fair).
# =======================================================================================
def keep_decisions(sel, cands, by_inst, q):
    """Per verb instance keep the argmax-sel candidate iff its sel >= per-arm quantile(q) over all cand sels.
    Returns kept = list of (sid, (v_surf, a, p)) for score_arm/subcat reuse."""
    all_sels = [sel(c["v"], c["p"]) for c in cands]
    thr = float(np.quantile(all_sels, q)) if all_sels else 0.0
    kept = []
    for (sid, vl), idxs in by_inst.items():
        bi, bs = argmax_pick(sel, cands, idxs)
        if bi is not None and bs >= thr:
            c = cands[bi]
            kept.append((sid, (c["v_surf"], c["a"], c["p"])))
    return kept, thr


def f1_sweep(sel, cands, by_inst, gold):
    out = {}
    best_q, best_f1 = None, -1.0
    for q in Q_SWEEP:
        kept, thr = keep_decisions(sel, cands, by_inst, q)
        sc = L.score_arm(kept, gold)
        out[f"{q:.2f}"] = {"f1": sc["f1"], "precision": sc["precision"], "recall": sc["recall"],
                           "fp_rate": sc["fp_rate"], "n_pred": sc["n_pred"], "thr": round(thr, 5)}
        if sc["f1"] > best_f1:
            best_f1, best_q = sc["f1"], q
    return out, best_q


# =======================================================================================
# Error decomposition (extraction-vs-disambiguation, the honest crux).
# =======================================================================================
def error_decomposition(thin, rich, gold, by_inst, cands):
    """Over all gold-pos items: RECALL_MISS (gold patient not a candidate) vs DISAMBIG (present).
    Within DISAMBIG report thin-correct / rich-correct picks (pure argmax, no threshold)."""
    n_pos = 0
    recall_miss = 0
    disambig_total = 0
    thin_pick_ok = 0
    rich_pick_ok = 0
    rich_fixes = 0                      # thin wrong, rich right
    rich_breaks = 0                     # thin right, rich wrong
    for sid, rec in gold.items():
        for g in rec["pos"]:
            n_pos += 1
            idxs = by_inst.get((sid, g["v"]), [])
            patients = [cands[i]["p"] for i in idxs]
            if g["patient"] not in patients:
                recall_miss += 1
                continue
            disambig_total += 1
            bt, _ = argmax_pick(thin, cands, idxs)
            br, _ = argmax_pick(rich, cands, idxs)
            t_ok = (cands[bt]["p"] == g["patient"]) if bt is not None else False
            r_ok = (cands[br]["p"] == g["patient"]) if br is not None else False
            thin_pick_ok += 1 if t_ok else 0
            rich_pick_ok += 1 if r_ok else 0
            if (not t_ok) and r_ok:
                rich_fixes += 1
            if t_ok and (not r_ok):
                rich_breaks += 1
    return {
        "n_gold_pos": n_pos,
        "recall_miss": recall_miss,
        "recall_miss_fraction": round(recall_miss / max(1, n_pos), 4),
        "recall_ceiling": round(1.0 - recall_miss / max(1, n_pos), 4),
        "disambig_total": disambig_total,
        "thin_pick_correct": thin_pick_ok,
        "rich_pick_correct": rich_pick_ok,
        "rich_fixes_thin_errors": rich_fixes,
        "rich_breaks_thin_correct": rich_breaks,
        "net_disambig_gain": rich_fixes - rich_breaks,
    }


