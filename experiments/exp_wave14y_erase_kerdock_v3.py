"""Bet 2 v3 - 4-coset Kerdock-like codebook via Maiorana-McFarland construction.

v2 validated the structured-keys story at M_stored <= 2N (= 8192) with a
2-coset codebook. v3 extends to M_stored up to 4N (= 16384) using 4 cosets
generated by the Maiorana-McFarland construction over GF(2^t):

  For k = 2t, b in GF(2^t):
    Q_b(x_lo, x_hi) = x_lo . (b * x_hi) over GF(2)
    q_b[x] = (-1)^{Q_b(x_lo, x_hi)}
    Coset b: row a -> H[a] * q_b (element-wise)

For 4 distinct b values (e.g. {0, 1, alpha, alpha^2}), all 6 pairwise XORs
are also Q_b' for some b' != 0, hence bent by construction. The codebook
has 4N codewords with pairwise IPs in {0, +/- 1/sqrt(N)} (Welch bound).

Two arms, same script (matches v2 layout):
  Kerdock: 4-coset MM codebook with snap-to-codebook on paraphrase
  Correlated: rank-L correlated keys (matches v1/v2's failing control)

Multi-probe at M_stored = {4096, 8192, 12288, 16384} = {N, 2N, 3N, 4N}.

Pre-reg: preregs/2026-05-21_wave14y_erase_kerdock_v3.md
"""
