def build_gf2t_tables(t: int) -> tuple[list[int], list[int]]:
    """Build log and antilog tables for GF(2^t) using PRIMITIVE_POLY[t].
    Returns (log_table, antilog_table).
      log_table[v] = i such that v = alpha^i; log_table[0] = -1
      antilog_table[i] = alpha^i (for i in 0..2^t-2)
    """
    if t not in PRIMITIVE_POLY:
        raise ValueError(f"No primitive polynomial registered for GF(2^{t})")
    poly = PRIMITIVE_POLY[t]
    field_size = 1 << t
    period = field_size - 1
    antilog = [0] * period
    log_table = [-1] * field_size
    val = 1
    for i in range(period):
        antilog[i] = val
        log_table[val] = i
        val <<= 1
        if val & field_size:  # bit at degree t -> reduce
            val ^= poly
        val &= field_size - 1
    return log_table, antilog


def gf2t_mul(a: int, b: int, log_tab: list, antilog_tab: list, period: int) -> int:
    if a == 0 or b == 0:
        return 0
    return antilog_tab[(log_tab[a] + log_tab[b]) % period]


def build_q_b_signs(b: int, N: int, t: int, log_tab: list, antilog_tab: list,
                      device: torch.device) -> torch.Tensor:
    """Build q_b sign vector of length N for the MM quadratic Q_b.

    Q_b(x_lo, x_hi) = x_lo . (b * x_hi) over GF(2), where * is GF(2^t)
    multiplication and . is dot product (popcount mod 2).
    """
    period = (1 << t) - 1
    half_mask = (1 << t) - 1
    q = torch.empty(N, dtype=torch.float32, device=device)
    for x in range(N):
        x_lo = x & half_mask
        x_hi = (x >> t) & half_mask
        if b == 0:
            q[x] = 1.0  # Q_0(x) = 0
            continue
        pi_b_xhi = gf2t_mul(b, x_hi, log_tab, antilog_tab, period)
        # x_lo . pi_b_xhi over GF(2) = popcount(x_lo & pi_b_xhi) mod 2
        bit_count = bin(x_lo & pi_b_xhi).count('1')
        q[x] = -1.0 if (bit_count & 1) else 1.0
    return q


def make_kerdock_4coset_codebook(N: int, device: torch.device) -> tuple[torch.Tensor, dict]:
    """Build 4-coset MM-based codebook of 4N codewords at length N.

    N must be 2^k for even k. Uses GF(2^{k/2}) with primitive polynomial
    from PRIMITIVE_POLY.

    Returns (codebook of shape (4N, N), info dict with construction details).
    """
    n_log2 = int(round(math.log2(N)))
    if 2 ** n_log2 != N:
        raise ValueError(f"N={N} must be power of 2")
    if n_log2 % 2 != 0:
        raise ValueError(f"N={N} requires even log2(N) for MM construction "
                         f"(got n_log2={n_log2})")
    t = n_log2 // 2

    log_tab, antilog_tab = build_gf2t_tables(t)
    H = v1.sylvester_hadamard(n_log2, device)  # (N, N)

    # b values: 0, 1, alpha, alpha^2. alpha is the primitive element = antilog[1].
    # antilog[0] = 1 (alpha^0), antilog[1] = alpha (= 2 in integer rep typically).
    alpha = antilog_tab[1]
    alpha_squared = antilog_tab[2]
    b_values = [0, 1, alpha, alpha_squared]

    cosets = []
    for b in b_values:
        q_b = build_q_b_signs(b, N, t, log_tab, antilog_tab, device)
        coset = H * q_b.unsqueeze(0)  # broadcast q_b across rows
        cosets.append(coset)
    codebook = torch.cat(cosets, dim=0)  # (4N, N)

    info = {
        "t": t,
        "primitive_poly": bin(PRIMITIVE_POLY[t]),
        "b_values": b_values,
        "n_cosets": len(b_values),
        "codebook_size": codebook.shape[0],
    }
    return codebook, info


def cell_passes(row: dict) -> tuple[bool, list[str]]:
    fails = []
    M = row.get("M_stored", 1)
    rank_thresh = max(2.0, M * PASS_RANK_FRAC)
    if row["argmax_leak"] >= PASS_ARGMAX:
        fails.append(f"argmax={row['argmax_leak']:.3f}")
    if row["mean_rank"] <= rank_thresh:
        fails.append(f"rank={row['mean_rank']:.1f}<={rank_thresh:.1f}")
    if row["norm_ratio"] >= PASS_NORM:
        fails.append(f"norm={row['norm_ratio']:.3f}")
    para_h8 = row.get("paraphrase_leak_h8", 1.0)
    if para_h8 >= PASS_PARAPHRASE:
        fails.append(f"para_h8={para_h8:.3f}")
    if row["kept_preservation"] < PASS_KEPT:
        fails.append(f"kept={row['kept_preservation']:.3f}")
    return (len(fails) == 0, fails)


def compute_verdict(summary: dict) -> tuple[str, str]:
    arms = summary.get("by_arm", {})
    if "kerdock" not in arms or "correlated" not in arms:
        return ("KERDOCK_V3_INCONCLUSIVE", "Missing per-arm data.")
    N = summary.get("N", N_FULL)
    kerdock_rows = arms["kerdock"].get("per_M", [])
    correlated_rows = arms["correlated"].get("per_M", [])
    if not kerdock_rows or not correlated_rows:
        return ("KERDOCK_V3_INCONCLUSIVE", "Empty per-M rows.")

    kerdock_pass = {r["M_stored"]: cell_passes(r) for r in kerdock_rows}
    corr_pass = {r["M_stored"]: cell_passes(r) for r in correlated_rows}
    ms_sorted = sorted(kerdock_pass.keys())

    # If correlated arm passes everywhere, audit needed
    if all(corr_pass[m][0] for m in ms_sorted):
        return ("KERDOCK_V3_CORRELATED_PASSES",
                f"Correlated arm passes all probes at every tested M_stored. "
                f"Cannot attribute Kerdock outcome to structure. Audit setup vs v2.")

    # Find largest M_stored where Kerdock passes
    largest_kerdock_pass = max((m for m in ms_sorted if kerdock_pass[m][0]),
                                  default=None)
    first_kerdock_fail = next((m for m in ms_sorted if not kerdock_pass[m][0]),
                                 None)

    if first_kerdock_fail is None:
        return ("KERDOCK_V3_EXTENDS_TO_4N",
                f"Kerdock arm passes at all M_stored in {ms_sorted} (up to "
                f"{max(ms_sorted)} = {max(ms_sorted)/N:.2f}*N). Correlated arm "
                f"fails as expected. Welch-bound structured codebook extends "
                f"Mirage protection through 4N at N={N}.")

    return (f"KERDOCK_V3_DECAYS_AT_{first_kerdock_fail}",
            f"Kerdock arm holds up to M_stored={largest_kerdock_pass}; fails at "
            f"M_stored={first_kerdock_fail} with: "
            f"{'; '.join(kerdock_pass[first_kerdock_fail][1])}. Envelope sized "
            f"at M_stored={largest_kerdock_pass} (= {largest_kerdock_pass/N:.2f}*N).")


def self_test_verdict() -> None:
    N_test = 4096

    def mk_row(M, args):
        rank_default = max(2.0, M * PASS_RANK_FRAC * 2)
        return {"M_stored": M,
                "argmax_leak": args.get("a", 0.02),
                "mean_rank": args.get("r", rank_default),
                "norm_ratio": args.get("n", 0.05),
                "paraphrase_leak_h8": args.get("p", 0.02),
                "kept_preservation": args.get("k", 0.98)}

    pass_args = {}
    fail_args = {"a": 0.20}

    cases = [
        # 1. EXTENDS_TO_4N: all M pass for kerdock; correlated fails somewhere
        ({"N": N_test, "by_arm": {
            "kerdock": {"per_M": [mk_row(m, pass_args)
                                    for m in [4096, 8192, 12288, 16384]]},
            "correlated": {"per_M": [mk_row(4096, fail_args),
                                       mk_row(8192, fail_args),
                                       mk_row(12288, fail_args),
                                       mk_row(16384, fail_args)]}}},
         "KERDOCK_V3_EXTENDS_TO_4N"),
        # 2. DECAYS_AT_12288: kerdock fails at 12288
        ({"N": N_test, "by_arm": {
            "kerdock": {"per_M": [mk_row(4096, pass_args), mk_row(8192, pass_args),
                                    mk_row(12288, fail_args),
                                    mk_row(16384, fail_args)]},
            "correlated": {"per_M": [mk_row(4096, fail_args), mk_row(8192, fail_args),
                                       mk_row(12288, fail_args),
                                       mk_row(16384, fail_args)]}}},
         "KERDOCK_V3_DECAYS_AT_12288"),
        # 3. CORRELATED_PASSES
        ({"N": N_test, "by_arm": {
            "kerdock": {"per_M": [mk_row(m, pass_args)
                                    for m in [4096, 8192, 12288, 16384]]},
            "correlated": {"per_M": [mk_row(m, pass_args)
                                       for m in [4096, 8192, 12288, 16384]]}}},
         "KERDOCK_V3_CORRELATED_PASSES"),
        # 4. INCONCLUSIVE
        ({"N": N_test, "by_arm": {}}, "KERDOCK_V3_INCONCLUSIVE"),
    ]
    for s, expected in cases:
        actual, msg = compute_verdict(s)
        if actual != expected:
            raise AssertionError(f"FAIL: actual={actual} != expected={expected} msg={msg}")
    print(f"verdict self-test passed ({len(cases)}/{len(cases)} cases)", flush=True)


def sample_kerdock_keys(codebook: torch.Tensor, n_keys: int,
                          cpu_gen: torch.Generator, device: torch.device) -> torch.Tensor:
    M_book = codebook.size(0)
    if n_keys > M_book:
        raise ValueError(f"Requested {n_keys} keys but codebook has only {M_book}.")
    perm = torch.randperm(M_book, generator=cpu_gen)[:n_keys].to(device)
    return codebook[perm]


def run_arm(arm_name: str, codebook: torch.Tensor | None, M_stored_list: list,
             config: dict, device: torch.device) -> dict:
    N = config["N"]
    n_erase = config["n_erase"]
    n_kept = config["n_kept_probe"]
    hamming = config["hamming_radii"]
    n_para = config["n_paraphrase"]
    seeds = config["seeds"]

    per_M = []
    for M_stored in M_stored_list:
        per_seed = []
        for seed in seeds:
            gen = torch.Generator(device=device).manual_seed(seed)
            cpu_gen = torch.Generator().manual_seed(seed + 1009)

            if codebook is not None:
                keys = sample_kerdock_keys(codebook, M_stored, cpu_gen, device)
            else:
                rank_L = max(2, int(M_stored * 0.25))
                keys = v1.make_correlated_keys(M_stored, N, rank_L, gen, device)

            values = 2.0 * (torch.rand((M_stored, N), generator=gen,
                                          device=device) > 0.5).float() - 1.0
            W = (values.T @ keys) / N

            erase_gen = torch.Generator().manual_seed(seed * 31 + 7)
            kept_gen = torch.Generator().manual_seed(seed * 31 + 11)
            erase_idx = sorted(torch.randperm(M_stored, generator=erase_gen)[:n_erase].tolist())
            erase_set = set(erase_idx)
            candidates = [i for i in range(M_stored) if i not in erase_set]
            n_kept_actual = min(n_kept, len(candidates))
            kept_idx = sorted(torch.tensor(candidates)[torch.randperm(
                len(candidates), generator=kept_gen)[:n_kept_actual]].tolist())

            W_edit = W.clone()
            for i in erase_idx:
                W_edit = v1.antihebbian_erase(W_edit, keys[i], ALPHA)

            probe = v2.multi_probe_with_snap(W_edit, keys, values, erase_idx, kept_idx,
                                                hamming, n_para, codebook, cpu_gen, device)
            probe["seed"] = seed
            per_seed.append(probe)

        def avg(k):
            vals = [r[k] for r in per_seed if k in r]
            return sum(vals) / len(vals) if vals else 0.0

        row = {"M_stored": M_stored,
                "argmax_leak": avg("argmax_leak"),
                "mean_rank": avg("mean_rank"),
                "norm_ratio": avg("norm_ratio"),
                "cosine": avg("cosine"),
                "kept_preservation": avg("kept_preservation"),
                "per_seed": per_seed}
        for h in hamming:
            row[f"paraphrase_leak_h{h}"] = avg(f"paraphrase_leak_h{h}")
        per_M.append(row)

    return {"per_M": per_M}


def run_experiment(smoke: bool):
    t_start = time.monotonic()
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    config = {
        "mode": "smoke" if smoke else "full",
        "N": N_SMOKE if smoke else N_FULL,
        "M_stored_list": M_STORED_SMOKE if smoke else M_STORED_FULL,
        "n_erase": N_ERASE_SMOKE if smoke else N_ERASE_FULL,
        "n_kept_probe": N_KEPT_PROBE_SMOKE if smoke else N_KEPT_PROBE_FULL,
        "n_paraphrase": N_PARAPHRASE,
        "hamming_radii": HAMMING_RADII_SMOKE if smoke else HAMMING_RADII_FULL,
        "seeds": SEEDS_SMOKE if smoke else SEEDS_FULL,
        "alpha": ALPHA,
    }
    print(f"[config] {config}", flush=True)
    print(f"[device] {device}", flush=True)

    print(f"[codebook] building 4-coset MM codebook at N={config['N']}...", flush=True)
    codebook, info = make_kerdock_4coset_codebook(config["N"], device)
    print(f"[codebook] {info}", flush=True)

    # Codebook self-checks (used for smoke oracle too)
    N = config["N"]
    book_ips = (codebook @ codebook.T) / N
    book_mask = ~torch.eye(codebook.size(0), dtype=torch.bool, device=device)
    off_diag = book_ips[book_mask].abs()
    book_max_abs = float(off_diag.max())
    # Per-coset within max
    n_cosets = info["n_cosets"]
    within_max = 0.0
    for c in range(n_cosets):
        coset = codebook[c * N:(c + 1) * N]
        ips = (coset @ coset.T) / N
        mask = ~torch.eye(N, dtype=torch.bool, device=device)
        within_max = max(within_max, float(ips[mask].abs().max()))
    print(f"[codebook] book_max_abs={book_max_abs:.6f}  "
          f"within_coset_max={within_max:.6f}  expected_cross=1/sqrt(N)={1.0/math.sqrt(N):.6f}",
          flush=True)

    print(f"[arm=kerdock] running...", flush=True)
    arm_k = run_arm("kerdock", codebook, config["M_stored_list"], config, device)
    print(f"[arm=correlated] running...", flush=True)
    arm_c = run_arm("correlated", None, config["M_stored_list"], config, device)

    summary = {
        "N": config["N"],
        "by_arm": {"kerdock": arm_k, "correlated": arm_c},
        "codebook_stats": {
            "size": codebook.shape[0],
            "info": info,
            "book_max_abs_ip": book_max_abs,
            "within_coset_max": within_max,
            "expected_welch_bound": 1.0 / math.sqrt(N),
        },
    }
    verdict, msg = compute_verdict(summary)
    elapsed = time.monotonic() - t_start

    print("\n========= ARM COMPARISON =========", flush=True)
    for arm_name, arm_data in summary["by_arm"].items():
        print(f"[{arm_name}]", flush=True)
        for row in arm_data["per_M"]:
            paras = " ".join(f"p_h{h}={row[f'paraphrase_leak_h{h}']:.3f}"
                              for h in config["hamming_radii"])
            print(f"  M={row['M_stored']:5d}  argmax={row['argmax_leak']:.3f}  "
                  f"rank={row['mean_rank']:.1f}  norm={row['norm_ratio']:.3f}  "
                  f"{paras}  kept={row['kept_preservation']:.3f}", flush=True)

    print(f"\nVERDICT: {verdict}\n  {msg}", flush=True)
    return summary, verdict, msg, elapsed, config


def write_metrics(out_dir: Path, summary, verdict, msg, elapsed, config):
    metrics = {"verdict": verdict, "verdict_msg": msg, "elapsed_s": elapsed,
                "summary": summary, "config": config}
    validate_metrics(metrics)
    tmp = out_dir / "metrics.json.tmp"
    tmp.write_text(json.dumps(metrics, indent=2, default=float))
    tmp.replace(out_dir / "metrics.json")


def run_smoke():
    out_dir = get_output_dir("wave14y_erase_kerdock_v3_smoke")
    log_event("experiment_started", name="wave14y_erase_kerdock_v3", mode="smoke")
    summary, verdict, msg, elapsed, config = run_experiment(smoke=True)

    # Oracle 1: codebook cross-coset max IP exactly the Welch bound
    N = config["N"]
    expected = 1.0 / math.sqrt(N)
    max_abs = summary["codebook_stats"]["book_max_abs_ip"]
    # Tight band: within 5% of expected (MM construction is exact)
    band_lo = expected * 0.95
    band_hi = expected * 1.05
    oracle.assert_in_range("kerdock_v3_welch_bound", max_abs, (band_lo, band_hi))

    # Oracle 2: within-coset IPs near zero
    within = summary["codebook_stats"]["within_coset_max"]
    if within > 1e-5:
        raise AssertionError(
            f"SANITY FAIL [within_coset]: max within-coset IP = {within:.6f} > 1e-5; "
            f"Hadamard rows not orthogonal within coset after q_b multiplication")

    # Oracle 3: snap identity
    codebook, _ = make_kerdock_4coset_codebook(N, torch.device("cpu"))
    sample = codebook[:5]
    snapped = v2.snap_to_codebook_batch(sample, codebook)
    if not torch.equal(snapped, sample):
        raise AssertionError(
            "SANITY FAIL [snap_identity]: snap(c) != c for c in codebook")

    write_metrics(out_dir, summary, verdict, msg, elapsed, config)
    log_event("experiment_outcome", name="wave14y_erase_kerdock_v3",
              mode="smoke", verdict=verdict, verdict_msg=msg, elapsed_s=elapsed)
    print(f"\nSMOKE OK: {verdict}", flush=True)


def run_main():
    out_dir = get_output_dir("wave14y_erase_kerdock_v3")
    log_event("experiment_started", name="wave14y_erase_kerdock_v3", mode="full")
    summary, verdict, msg, elapsed, config = run_experiment(smoke=False)
    write_metrics(out_dir, summary, verdict, msg, elapsed, config)
    log_event("experiment_outcome", name="wave14y_erase_kerdock_v3",
              mode="full", verdict=verdict, verdict_msg=msg, elapsed_s=elapsed)
    print(f"\nDONE: {verdict}", flush=True)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--self-test", action="store_true")
    ap.add_argument("--smoke", action="store_true")
    args = ap.parse_args()
    if args.self_test:
        self_test_verdict()
        return 0
    if args.smoke:
        run_smoke()
        return 0
    run_main()
    return 0


