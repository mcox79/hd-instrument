# Primitive polynomials for GF(2^t) used here (degree, polynomial integer rep).
# Each polynomial = x^t + ... + 1; bit i = coefficient of x^i.
# Standard choices that yield primitive elements with maximal period 2^t-1.
PRIMITIVE_POLY = {
    5: 0b100101,     # x^5 + x^2 + 1   (degree 5, length-6 bitstring)
    6: 0b1000011,    # x^6 + x + 1     (degree 6, length-7 bitstring)
    7: 0b10000011,   # x^7 + x + 1     (degree 7, length-8 bitstring; standard primitive per Lidl-Niederreiter table)
}


