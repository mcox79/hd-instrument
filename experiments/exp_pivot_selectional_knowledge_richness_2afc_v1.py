def load_rich_table():
    if not os.path.exists(RICH_TABLE_PATH):
        return None
    with open(RICH_TABLE_PATH, encoding="utf-8") as f:
        obj = json.load(f)
    tab = {}
    for k, val in obj.get("ratings", obj).items():
        if "|" in k:
            v, n = k.split("|", 1)
            tab[(v, n)] = float(val)
    return tab


def _2afc(items, score_of):
    """score_of: (v,noun)->float. Returns accuracy (tie=0.5), per-item correctness, per-stratum acc."""
    correct = 0.0
    per_item = []
    strat = defaultdict(lambda: [0.0, 0])
    for it in items:
        sp = score_of(it["v"], it["gold_patient"])
        sn = score_of(it["v"], it["neg_filler"])
        c = 1.0 if sp > sn else (0.5 if sp == sn else 0.0)
        correct += c
        strat[it["neg_stratum"]][0] += c
        strat[it["neg_stratum"]][1] += 1
        per_item.append(round(c, 2))
    n = len(items)
    strat_acc = {k: round(v[0] / max(1, v[1]), 4) for k, v in sorted(strat.items())}
    strat_n = {k: v[1] for k, v in sorted(strat.items())}
    return round(correct / max(1, n), 4), per_item, strat_acc, strat_n


def make_random_score():
    rng = np.random.default_rng(NEG_SEED + 7)
    cache = {}

    def s(v, p):
        k = (v, p)
        if k not in cache:
            cache[k] = float(rng.random())
        return cache[k]
    return s


def make_scrambled_rich(rich_tab):
    """Permute rich VALUES across the pair keys (must-fail knowledge-content control)."""
    keys = sorted(rich_tab.keys())
    vals = [rich_tab[k] for k in keys]
    rng = np.random.default_rng(NEG_SEED + 9)
    perm = rng.permutation(len(vals)).tolist()
    scr = {keys[i]: vals[perm[i]] for i in range(len(keys))}

    def s(v, p):
        return scr.get((v, p), 0.5)
    return s


def make_rich_at_coverage(rich_tab, thin_score, f):
    """Keep fraction f of rich entries (fixed-seed subsample); backoff to THIN for the rest."""
    keys = sorted(rich_tab.keys())
    rng = np.random.default_rng(NEG_SEED + 11)
    order = rng.permutation(len(keys)).tolist()
    keep = set(keys[order[i]] for i in range(int(round(f * len(keys)))))

    def s(v, p):
        k = (v, p)
        if k in keep:
            return rich_tab[k]
        return thin_score(v, p)[0]
    return s


