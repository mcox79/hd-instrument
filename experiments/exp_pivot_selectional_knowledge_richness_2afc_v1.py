def build_thin_gfit(mode):
    files = SCV.MINING_FILES_SMOKE if mode == "smoke" else SCV.MINING_FILES_FULL
    out_dir = _out_dir(mode)
    cache = os.path.join(out_dir, "_mining_cache.json")
    mine_data = SCV.run_reader_on_files(files, cache, max_sents=(600 if mode == "smoke" else None))
    bare = []
    for sid, rec in mine_data.items():
        toks = L.tokenize(rec["sent"])
        for tup in rec["svo"]:
            v_surf, a, p = tup
            feat6, _ = L.candidate_features(toks, v_surf, p)
            bare.append({"sid": sid, "v": L.lemma_verb(v_surf), "a": a, "p": p,
                         "feat6": np.asarray(feat6, dtype=np.float64)})
    gfit_fn, stats = G.build_gfit_model(bare)

    def thin_score(v, p):
        s, kind = gfit_fn(v, p)
        return (0.5 if s is None else float(s)), kind   # OOV -> neutral 0.5 (no signal = the poverty)
    return thin_score, stats, len(mine_data)


