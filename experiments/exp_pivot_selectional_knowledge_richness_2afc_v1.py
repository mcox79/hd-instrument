# Self-test (constructs REAL items + REAL thin gfit at tiny scale; asserts arms + 2AFC mechanics fire).
# ----------------------------------------------------------------------------------------------
def self_test():
    # 1) item construction is deterministic + well-formed
    items = build_items()
    assert 10 <= len(items) <= MAX_ITEMS, f"expected 10..{MAX_ITEMS} items, got {len(items)}"
    for it in items:
        assert it["gold_patient"] != it["neg_filler"], "gold and negative must differ"
        assert _is_content_noun(it["gold_patient"]) and _is_content_noun(it["neg_filler"]), "content nouns only"
        assert it["neg_stratum"] in ("same_class", "cross_class", "fallback")
    items2 = build_items()
    assert [ (i["v"], i["gold_patient"], i["neg_filler"]) for i in items ] == \
           [ (i["v"], i["gold_patient"], i["neg_filler"]) for i in items2 ], "item build must be deterministic"

    # 2) REAL thin gfit constructed at SMOKE scale (exercises the prior mechanism's real code path)
    thin_score, stats, n_mine = build_thin_gfit("smoke")
    assert stats["n_object_classes"] >= 1 and n_mine > 0, "thin gfit must build on real corpus"
    s_def, k_def = thin_score(items[0]["v"], items[0]["gold_patient"])
    assert 0.0 <= s_def <= 1.0, "thin score in [0,1]"
    assert thin_score("qzxwv", "qzxwv")[0] == 0.5, "OOV backs off to neutral 0.5"

    # 3) 2AFC mechanics + a toy rich table -> arms differ + scramble collapses a rigged perfect table
    toy_items = [{"v": "eat", "gold_patient": "apple", "neg_filler": "stone", "neg_stratum": "cross_class",
                  "gold_ss": "noun.food", "neg_ss": "noun.object"},
                 {"v": "ride", "gold_patient": "horse", "neg_filler": "cow", "neg_stratum": "same_class",
                  "gold_ss": "noun.animal", "neg_ss": "noun.animal"}]
    perfect = {("eat", "apple"): 0.95, ("eat", "stone"): 0.05,
               ("ride", "horse"): 0.9, ("ride", "cow"): 0.2}
    acc_perfect, _, _, _ = _2afc(toy_items, lambda v, p: perfect.get((v, p), 0.5))
    assert acc_perfect == 1.0, "a correct table must score 1.0 on the toy 2AFC"
    rng_arm = make_random_score()
    acc_r, _, _, _ = _2afc(toy_items, rng_arm)
    assert 0.0 <= acc_r <= 1.0, "random arm valid"
    scr = make_scrambled_rich(perfect)
    acc_scr, _, _, _ = _2afc(toy_items, scr)
    assert acc_scr <= acc_perfect, "scrambled must not exceed the correct table"
    # coverage f=0 must equal thin exactly (internal consistency of the curve)
    cov0 = make_rich_at_coverage(perfect, thin_score, 0.0)
    acc_cov0, _, _, _ = _2afc(toy_items, cov0)
    acc_thin_toy, _, _, _ = _2afc(toy_items, lambda v, p: thin_score(v, p)[0])
    assert abs(acc_cov0 - acc_thin_toy) < 1e-9, "coverage f=0 must equal ARM_THIN exactly"

    print(f"[{ANCHOR_NAME}] self-test PASS | n_items={len(items)} thin_classes={stats['n_object_classes']} "
          f"n_mine={n_mine} toy_perfect={acc_perfect} toy_scrambled={acc_scr} cov0==thin OK", flush=True)


