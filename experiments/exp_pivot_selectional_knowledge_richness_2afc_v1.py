def _is_content_noun(p):
    pl = p.lower()
    return (pl not in L.FUNCWORD and pl not in L.PREPS and pl not in L.PRONOUN
            and pl.replace("'", "").isalpha() and len(pl) >= 2)


def load_gold_pos_content_items():
    """Content-noun gold (verb_lemma, gold_patient) pos items with a defined WordNet supersense.
    Deterministic order (sorted). Excludes pronoun/funcword patients (not selectional)."""
    with open(GOLD_PATH, encoding="utf-8") as f:
        obj = json.load(f)
    seen = set()
    items = []
    attested = defaultdict(set)   # verb -> set of its gold patients (to exclude as negatives)
    pool_by_ss = defaultdict(set)  # supersense -> set of content-noun patients (negative candidate pool)
    all_pool = set()
    for sid, rec in sorted(obj["gold"].items()):
        if sid.split("_")[0] not in GOLD_SLICE:
            continue
        for r in rec.get("pos", []):
            v = L.lemma_verb(r["v"]).lower()
            p = r["patient"].lower()
            if not _is_content_noun(p):
                continue
            ss = SCV.supersense(p)
            if ss is None:                    # require a defined class so same-class sampling is controlled
                continue
            attested[v].add(p)
            pool_by_ss[ss].add(p)
            all_pool.add(p)
            key = (v, p)
            if key in seen:
                continue
            seen.add(key)
            items.append({"v": v, "gold_patient": p, "gold_ss": ss})
    return items, attested, pool_by_ss, all_pool


def sample_negatives(items, attested, pool_by_ss, all_pool):
    """For each item pick ONE negative filler (fixed RNG). Prefer SAME supersense class as the gold patient
    (HARD within-class regime = where the mapped ceiling lived); fall back cross-class. Never the gold patient
    and never a noun attested as this verb's patient anywhere in gold. Deterministic + resource-neutral."""
    rng = np.random.default_rng(NEG_SEED)
    for it in items:
        v, gp, ss = it["v"], it["gold_patient"], it["gold_ss"]
        excl = set(attested[v]) | {gp}
        same = sorted(pool_by_ss.get(ss, set()) - excl)
        cross = sorted(all_pool - excl - set(pool_by_ss.get(ss, set())))
        if same:
            neg = same[int(rng.integers(len(same)))]
            it["neg_stratum"] = "same_class"
        elif cross:
            neg = cross[int(rng.integers(len(cross)))]
            it["neg_stratum"] = "cross_class"
        else:
            neg = sorted(all_pool - {gp})[int(rng.integers(max(1, len(all_pool) - 1)))]
            it["neg_stratum"] = "fallback"
        it["neg_filler"] = neg
        it["neg_ss"] = SCV.supersense(neg)
    return items


def build_items():
    items, attested, pool_by_ss, all_pool = load_gold_pos_content_items()
    items = sorted(items, key=lambda d: (d["v"], d["gold_patient"]))   # deterministic
    if len(items) > MAX_ITEMS:
        rng = np.random.default_rng(NEG_SEED + 1)
        idx = sorted(rng.permutation(len(items))[:MAX_ITEMS].tolist())
        items = [items[i] for i in idx]
    items = sample_negatives(items, attested, pool_by_ss, all_pool)
    return items


def unique_pairs(items):
    """Flat sorted-then-shuffled deduped (verb,noun) list -> what the LLM rates (UNLABELED)."""
    pairs = set()
    for it in items:
        pairs.add((it["v"], it["gold_patient"]))
        pairs.add((it["v"], it["neg_filler"]))
    ps = sorted(pairs)
    rng = np.random.default_rng(NEG_SEED + 2)
    order = rng.permutation(len(ps)).tolist()
    return [{"verb": ps[i][0], "noun": ps[i][1]} for i in order]


