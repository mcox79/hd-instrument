# =========================================================================== S_READ (real reading)
def build_reading_facts(process_filter=None) -> Dict[str, Dict[str, Dict[str, int]]]:
    """Real reading-extraction: (process, entity_head, fate) -> count, via the REAL v2
    high-precision extractor over the REAL dense process-articles corpus. Returns
    {process: {entity_head: {fate: count}}}."""
    from experiments.exp_stated_entity_fate_reading_extractor_v2_highprecision import (
        extract_facts_strict, _load_or_build_frontend,
    )
    gen = _load_or_build_frontend()
    corpus = json.load(open(CORPUS_PATH, encoding="utf-8"))
    articles = corpus["articles"]
    out: Dict[str, Dict[str, Dict[str, int]]] = {}
    for proc in sorted(articles.keys()):
        if process_filter is not None and proc not in process_filter:
            continue
        title_map = articles[proc]
        for title in sorted(title_map.keys()):
            for s in title_map[title]:
                s = s.strip()
                if not s:
                    continue
                for f in extract_facts_strict(gen, s):
                    ent, fate = f["entity_head"], f["fate"]
                    out.setdefault(proc, {}).setdefault(ent, {})
                    out[proc][ent][fate] = out[proc][ent].get(fate, 0) + 1
    return out


def reading_vocab(reading: Dict[str, Dict[str, Dict[str, int]]]) -> List[str]:
    v = set()
    for ents in reading.values():
        v.update(ents.keys())
    return sorted(v)


def reading_fact_set(reading: Dict[str, Dict[str, Dict[str, int]]]):
    s = set()
    for p, ents in reading.items():
        for e, fates in ents.items():
            for f in fates:
                s.add((p, e, f))
    return s


# =========================================================================== S_CSKG (bridges)
def build_cskg_bridges(vocab: List[str]) -> Tuple[Dict[str, List[str]], Dict[str, List[Tuple[str, str]]]]:
    """Single pass over all CSKG shards. Returns (narrow, wide):
      narrow[material] = [whole, ...]   from /r/MadeOf edges (whole, MadeOf, material), whole!=material
      wide[material]   = [whole, ...]   from ANY relation touching material (either direction), whole!=material
    Both deterministic (sorted() applied by caller where order matters)."""
    vset = set(vocab)
    narrow: Dict[str, List[str]] = {}
    wide: Dict[str, List[str]] = {}
    for fn in sorted(glob.glob(CSKG_GLOB)):
        with open(fn, encoding="utf-8") as f:
            for line in f:
                row = json.loads(line)
                s, o, rel = row["subject"], row["obj"], row["relation"]
                if o in vset and s != o:
                    wide.setdefault(o, []).append(s)
                    if rel == "/r/MadeOf":
                        narrow.setdefault(o, []).append(s)
                if s in vset and s != o:
                    wide.setdefault(s, []).append(o)
    return narrow, wide


def causenet_leak_check(procs: List[str], wholes: List[str]) -> Dict:
    """Full-file streaming scan of CauseNet-precision for any literal (process, whole) causal
    pair (either direction). Real absence-in-CauseNet audit, not assumed. FULL-mode only (~80s)."""
    terms = set(procs) | set(wholes)
    n_scanned = 0
    n_vocab_hits = 0
    literal_leaks = []
    gold_pairs = set((p, w) for p in procs for w in wholes)  # oversized but cheap membership set
    with bz2.open(CAUSENET_PATH, "rt", encoding="utf-8") as f:
        for line in f:
            n_scanned += 1
            row = json.loads(line)
            cr = row["causal_relation"]
            c, e = cr["cause"]["concept"], cr["effect"]["concept"]
            if c in terms or e in terms:
                n_vocab_hits += 1
                if (c, e) in gold_pairs or (e, c) in gold_pairs:
                    literal_leaks.append((c, e))
    return {"n_scanned": n_scanned, "n_vocab_hits": n_vocab_hits, "n_literal_leaks": len(literal_leaks),
            "literal_leaks": literal_leaks[:20]}


# =========================================================================== gap-set construction
def build_gap_set(reading, narrow) -> List[Dict]:
    """Programmatic, deterministic, audited gap-set construction: cross reading (P,C,F) facts
    with CSKG-narrow (whole MadeOf C) edges; absence-filter against reading's own fact set.
    Returns sorted list of {"process","whole","fate","via_material"} dicts (deduped)."""
    reading_set = reading_fact_set(reading)
    raw = []
    for proc in sorted(reading.keys()):
        for material in sorted(reading[proc].keys()):
            wholes = narrow.get(material, [])
            for whole in sorted(set(wholes)):
                if whole == material:
                    continue
                for fate in sorted(reading[proc][material].keys()):
                    raw.append({"process": proc, "whole": whole, "fate": fate, "via_material": material})
    survive = [c for c in raw if (c["process"], c["whole"], c["fate"]) not in reading_set]
    seen: Dict[Tuple[str, str, str], Dict] = {}
    for c in survive:
        k = (c["process"], c["whole"], c["fate"])
        if k not in seen:
            seen[k] = c
    targets = [seen[k] for k in sorted(seen.keys())]
    return {"raw_n": len(raw), "survive_n": len(survive), "unique_n": len(targets), "targets": targets}


# =========================================================================== entity/relation codebook
def build_entity_index(processes, materials, wholes) -> Tuple[List[str], Dict[str, int]]:
    ents: List[str] = []
    seen = set()
    for group in (sorted(processes), sorted(materials), sorted(wholes)):
        for name in group:
            if name not in seen:
                seen.add(name)
                ents.append(name)
    return ents, {name: i for i, name in enumerate(ents)}


def fresh_kg(n_ent: int, seed: int) -> KGStore:
    gen = torch.Generator().manual_seed(seed)
    return KGStore(n_ent=n_ent, n_rel=len(FATE_RELS) + 1, n_dim=KG_DIM, generator=gen)


def ingest_reading_hop1(kg: KGStore, reading, ent_idx: Dict[str, int]):
    rel_idx = {r: i for i, r in enumerate(FATE_RELS + [BRIDGE_REL])}
    rows = []
    for proc in sorted(reading.keys()):
        if proc not in ent_idx:
            continue
        for material in sorted(reading[proc].keys()):
            if material not in ent_idx:
                continue
            for fate, count in sorted(reading[proc][material].items()):
                for _ in range(count):
                    rows.append((ent_idx[proc], rel_idx[fate], ent_idx[material]))
    if rows:
        kg.ingest_triples(torch.tensor(rows, dtype=torch.long))
    return rel_idx


def ingest_bridge_hop2(kg: KGStore, edges: List[Tuple[str, str]], ent_idx: Dict[str, int], bridge_idx: int):
    """edges: list of (material, whole) pairs -> ingest (material, BRIDGE, whole) triples."""
    rows = []
    for material, whole in edges:
        if material in ent_idx and whole in ent_idx:
            rows.append((ent_idx[material], bridge_idx, ent_idx[whole]))
    if rows:
        kg.ingest_triples(torch.tensor(rows, dtype=torch.long))


# =========================================================================== fan-out reasoning
def fanout_query(hop1_kg: KGStore, hop2_kg: KGStore, start_idx: int, fate_idx: int, bridge_idx: int,
                  k1: int, k2: int, n_ent: int) -> List[Tuple[int, float]]:
    """K=2 fan-out + max-aggregate composition over KGStore.predict_one_hop_topk (the certified
    single-hop primitive naive_chain/predict_two_hop themselves call)."""
    k1e = min(k1, n_ent)
    idx1, sc1 = hop1_kg.predict_one_hop_topk(start_idx, fate_idx, k1e)
    agg: Dict[int, float] = {}
    k2e = min(k2, n_ent)
    for m_idx_t in idx1:
        m_idx = int(m_idx_t)
        idx2, sc2 = hop2_kg.predict_one_hop_topk(m_idx, bridge_idx, k2e)
        for w_idx_t, w_sc_t in zip(idx2, sc2):
            w_idx = int(w_idx_t)
            w_sc = float(w_sc_t)
            if w_idx not in agg or w_sc > agg[w_idx]:
                agg[w_idx] = w_sc
    ranked = sorted(agg.items(), key=lambda kv: (-kv[1], kv[0]))
    return ranked


def recovery_at(ranked: List[Tuple[int, float]], gold_idx: int, k: int) -> int:
    top = [idx for idx, _ in ranked[:k]]
    return int(gold_idx in top)


# =========================================================================== state-of-mind (arm 3)
def real_to_concat(v: torch.Tensor) -> np.ndarray:
    """FHRR complex64 -> real-valued concat(Re,Im); preserves the exact cleanup inner product
    (Re(conj(a).b) = dot(concat(Re(a),Im(a)), concat(Re(b),Im(b)))). See pre-reg for the identity."""
    return torch.cat([v.real, v.imag]).numpy().astype(np.float32)


def build_material_codebook(materials: List[str], seed: int):
    gen = torch.Generator().manual_seed(seed)
    vecs = {m: unit_phase_vec(FHRR_D, gen) for m in sorted(materials)}
    names = sorted(materials)
    codebook = np.stack([real_to_concat(vecs[m]) for m in names], axis=0)
    return names, codebook, vecs


def ca3_gather(process: str, reg: RelationRegister, material_names: List[str], codebook: np.ndarray,
               k_peel: int = CA3_K_PEEL, sim_floor: float = CA3_SIM_FLOOR) -> List[str]:
    """CA3-style relevance gather: peel-loop of hdlab.cleanup_family.iterative_attractor against
    the material codebook, decoding process's state-of-mind register (RelationRegister) one
    material at a time (matching-pursuit deflation), not a blind full scan."""
    query = real_to_concat(reg.decode_filler(process, "GOAL"))
    resid = query.copy()
    picked: List[str] = []
    picked_idx = set()
    for _ in range(k_peel):
        if float(np.linalg.norm(resid)) < 1e-6:
            break
        recovered, diag = cleanup_family.iterative_attractor(resid, codebook)
        idx = int(diag["final_argmax_idx"])
        cb_row = codebook[idx]
        denom = float(np.linalg.norm(resid) * np.linalg.norm(cb_row) + 1e-8)
        score = float(np.dot(resid, cb_row) / denom) if denom > 0 else 0.0
        if idx in picked_idx or score < sim_floor:
            break
        picked.append(material_names[idx])
        picked_idx.add(idx)
        resid = resid - cb_row
    return picked


# =========================================================================== voting (arm 2)
def voting_predict(process: str, reading, wide: Dict[str, List[str]], ent_idx: Dict[str, int]) -> List[Tuple[int, int]]:
    """Raw edge-count frequency over ALL wholes linked (any relation, WIDE pool) to ANY of
    process's own materials, regardless of fate match. No bind/unbind, no argmax chain."""
    counts: Dict[int, int] = {}
    for material in sorted(reading.get(process, {}).keys()):
        for whole in wide.get(material, []):
            if whole in ent_idx:
                w_idx = ent_idx[whole]
                counts[w_idx] = counts.get(w_idx, 0) + 1
    return sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))


# =========================================================================== scramble control
def scramble_edges(edges: List[Tuple[str, str]], seed: int) -> List[Tuple[str, str]]:
    """Fixed-seed permutation of the 'whole' endpoint across all (material,whole) edges,
    preserving each material's out-degree and the overall whole multiset."""
    materials = [m for m, _ in edges]
    wholes = [w for _, w in edges]
    rng = np.random.default_rng(seed)
    perm = rng.permutation(len(wholes))
    wholes_shuf = [wholes[i] for i in perm]
    return list(zip(materials, wholes_shuf))


# =========================================================================== self-test
def run_self_test() -> Dict:
    """Tiny synthetic fixture (N~16 entities), real objects, real code path. Plants ONE
    cross-source chain (whole0 MadeOf material0; process0 DESTROY material0) absent as a direct
    (process0, whole0, DESTROY) edge. Asserts: (a) arm0 structural check reports absent; (b) arm3
    (real RelationRegister + real iterative_attractor peel + real KGStore fan-out) recovers
    whole0 at top-1; (c) arm2 (voting, no fate-awareness) fails once a same-material
    different-fate distractor whole is added."""
    processes = ["process0", "process1"]
    materials = ["material0", "material1"]
    wholes = ["whole0", "whole1", "distractor_whole"]
    ents, ent_idx = build_entity_index(processes, materials, wholes)
    n_ent = len(ents)
    assert n_ent == 7, ents

    reading = {
        "process0": {"material0": {"DESTROY": 1}},
        "process1": {"material1": {"CREATE": 1}},
    }
    # arm0: (process0, whole0, DESTROY) absent from reading -> structural zero
    assert ("process0", "whole0", "DESTROY") not in reading_fact_set(reading)

    hop1 = fresh_kg(n_ent, SEED_KG)
    rel_idx = ingest_reading_hop1(hop1, reading, ent_idx)
    bridge_idx = rel_idx[BRIDGE_REL]

    # narrow bridge: whole0 MadeOf material0 (real chain); distractor_whole MadeOf material1
    # with a DIFFERENT fate (CREATE not DESTROY) -- voting (arm2, no fate-awareness) will be
    # pulled toward whichever material has more edges/co-occurrence, not the fate-correct one.
    hop2_cued = fresh_kg(n_ent, SEED_KG)
    ingest_bridge_hop2(hop2_cued, [("material0", "whole0")], ent_idx, bridge_idx)

    # arm3: CA3 gather should recover material0 as process0's own material, then fan-out finds whole0.
    mat_names, codebook, mat_vecs = build_material_codebook(materials, SEED_FHRR)
    gen_reg = torch.Generator().manual_seed(SEED_FHRR + 1)
    reg = RelationRegister(d=FHRR_D, generator=gen_reg)
    for proc in processes:
        for material in reading.get(proc, {}):
            reg.bind_filler(proc, "GOAL", mat_vecs[material])
    gathered = ca3_gather("process0", reg, mat_names, codebook, k_peel=5)
    assert gathered == ["material0"], f"SELF_TEST FAIL: CA3 gather expected ['material0'], got {gathered}"

    ranked3 = fanout_query(hop1, hop2_cued, ent_idx["process0"], rel_idx["DESTROY"], bridge_idx,
                            k1=5, k2=5, n_ent=n_ent)
    gold_idx = ent_idx["whole0"]
    assert ranked3 and ranked3[0][0] == gold_idx, (
        f"SELF_TEST FAIL: arm3 fan-out expected top-1={gold_idx} (whole0), got {ranked3[:3]}")

    # arm2 voting: add a distractor whole tied to material0 via a DIFFERENT (irrelevant) route
    # with higher raw frequency than the real chain -- voting has no fate-awareness so it should
    # NOT reliably prefer the fate-correct whole0 once a higher-count distractor exists.
    wide = {"material0": ["whole0", "distractor_whole", "distractor_whole", "distractor_whole"]}
    reading_p0 = {"process0": reading["process0"]}
    ranked2 = voting_predict("process0", reading_p0, wide, ent_idx)
    assert ranked2[0][0] == ent_idx["distractor_whole"], (
        "SELF_TEST FAIL: voting arm expected to be misled by raw frequency (distractor "
        f"dominates), got top-1={ranked2[0]}")

    return {"n_ent": n_ent, "ca3_gathered": gathered, "arm3_top1_idx": ranked3[0][0],
            "arm3_gold_idx": gold_idx, "arm2_top1_idx": ranked2[0][0],
            "arm2_distractor_idx": ent_idx["distractor_whole"]}


